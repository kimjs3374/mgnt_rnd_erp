# 업종적합도 — 회사 데이터에서 어휘를 만든다. 코드에 업종을 박지 않는다
#
# 어휘를 하드코딩하면 다른 회사가 쓸 수 없고, 무엇보다 「우리 회사에 맞춰 튜닝했다」가
