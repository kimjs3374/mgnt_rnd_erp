def extract(ann: dict[str, Any], company: dict[str, Any],
            lexicon: list[dict] | None = None) -> dict[str, Any]:
    """공고 한 건에서 특징을 뽑는다. LLM 호출 0회.

    돌려주는 것
      features   : Feature 목록 (근거 없는 항목은 애초에 만들어지지 않는다)
      본문사용   : 본문을 실제로 읽었는가. False 면 판정은 메타 축만으로 한 것이다
      구역       : 찾아낸 절 이름들. 비어 있으면 조항을 구역별로 못 갈랐다는 뜻이다
    """
    본문 = ann.get("본문") or ""
    쓸만한본문 = len(strip_ws(본문)) >= MIN_BODY_CHARS

    # 첨부 원문이 없거나 너무 짧으면 API 요약으로 대신 읽는다. 실측: 836건 중 첨부가
    # 파싱된 건 53건(IRIS 14 + 기업마당 39)뿐이다 — 나머지는 수집 단계에서 첨부 자체를
    # 안 받는다(K-Startup 전부·기업마당 상당수). 근거·확신도는 그대로 남기되, 어느
    # 컬럼에서 읽었는지(본문출처)는 화면·리포트가 "진짜 첨부문서"와 "API 요약"을
    # 구분해 말할 수 있게 정직하게 남긴다 — 섞어서 "공고문을 읽었다"고 하지 않는다.
    본문출처 = "원문"
    쓸텍스트 = 본문
    if not 쓸만한본문:
        요약 = ann.get("요약") or ""
        if len(strip_ws(요약)) >= MIN_SUMMARY_CHARS:
            본문출처, 쓸텍스트, 쓸만한본문 = "요약", _linebreak_bullets(요약), True
        else:
            본문출처 = None

    feats: list[Feature] = []
    feats += meta_features(ann)
    feats += industry_features(ann, company)

    구역명: list[str] = []
    if 쓸만한본문:
        cs = chunks(쓸텍스트)
        spans = sections(쓸텍스트)          # 요약은 절 제목이 없어 보통 빈 목록 — 정직한 결과다
        tag_sections(cs, spans)
        구역명 = [s[2] for s in spans]

        # 렉시콘을 먼저 본다 — 사람이 짚어준 것이 정규식보다 우선이다
        feats += scan_lexicon(cs, lexicon)
        본특징 = {(f.특징키, f.규칙id) for f in feats if f.추출원 == "렉시콘"}
        for r in RULES:
            for f in r.scan(cs):
                if (f.특징키, f.규칙id) not in 본특징:
                    feats.append(f)
        if 본문출처 == "원문":
            feats += scan_documents(cs)     # 제출서류 사전은 요약 텍스트엔 적용하지 않는다 —
                                             # 요약은 서류 목록을 담을 만큼 길지 않고, 오탐 위험만 있다

        나이 = startup_age_feature(쓸텍스트, company)
        if 나이 is not None:
            feats.append(나이)
        업종전용 = exclusive_industry_feature(cs)
        if 업종전용 is not None:
            feats.append(업종전용)

    # 같은 (특징키, 규칙id) 중복 제거 — 신뢰도 높은 것을 남긴다
    최선: dict[tuple[str, str], Feature] = {}
    for f in feats:
        k = (f.특징키, f.규칙id)
        cur = 최선.get(k)
        if cur is None or f.규칙신뢰도 > cur.규칙신뢰도:
            최선[k] = f

    return {
        "features": list(최선.values()),
        "본문사용": 쓸만한본문,
        "본문출처": 본문출처,          # "원문"(첨부 HWP/PDF 파싱) | "요약"(API 요약) | None
        "본문길이": len(strip_ws(쓸텍스트)) if 쓸만한본문 else 0,
        "구역": 구역명,
        "엔진버전": ENGINE_VERSION,
    }
