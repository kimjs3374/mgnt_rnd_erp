def scan_documents(cs: list[Chunk]) -> list[Feature]:
    """제출서류 구역에서 사전에 있는 서류명을 찾는다.

    구역을 못 찾았으면 **아무것도 반환하지 않는다.** 문서 전체를 훑으면 본문에 스치듯
    언급된 서류(예: 「사업자등록증에 적힌 업종」)까지 요구서류로 잡힌다 —
    있는 척하는 목록이 없는 목록보다 나쁘다.
    """
    targets = [c for c in cs if c.구역 == "제출서류"]
    if not targets:
        return []

    out: list[Feature] = []
    본 = set()
    for c in targets:
        for 표준명, 표기들 in DOC_LEXICON:
            if 표준명 in 본:
                continue
            for 표기 in 표기들:
                if 표기 in c.flat.lower():
                    본.add(표준명)
                    out.append(Feature(
                        특징키="제출서류",
                        종류="정보",
                        규칙id=f"R-DOC-{표준명}",
                        규칙신뢰도=0.85,
                        추출원="본문",
                        근거문장=tidy(c.원문),
                        근거_위치=c.시작,
                        구역="제출서류",
                        값_텍스트=표준명,
                    ))
                    break
    return out


