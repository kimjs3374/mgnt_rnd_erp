# 절 제목 줄. 두 꼴이 있고, 가리는 방법이 다르다.
#
#   ① 번호형  「4-2.  신청자격」 · 「2. 사업자격 및 사업자 선정 제외대상」
#      번호가 앞에 있으면 제목이라고 봐도 된다.
#
#   ② 글머리형 「□ 신청자격」 · 「◇ 지원제외」
#      ⚠ 이건 **길이로 가려야 한다.** 같은 기호가 본문 글머리에도 쓰인다:
#        「□ 아래의 경우 지원대상에서 제외 처리되나, 선정평가일의 3영업일 전 …」
#        이 줄을 제목으로 받으면 「선정평가」에 걸려 **지원제외 구역이 17자로 잘렸다**
#        (실측 회귀: 부채비율·체납·참여제한 조항이 통째로 사라져 판정이 「가능」으로
#         뒤집혔다). 절 제목은 짧다 — 그 성질로 가른다.
#
# ⚠ ②를 아예 빠뜨렸을 때는 실측 공고 2건(id 3·14)의 구역이 **하나도 안 잡혀서**
#   「기업 참여 불가」 조항을 신청자격 구역으로 못 읽었다. 넣어야 하고, 좁혀야 한다.
_HEADING_NUM = re.compile(
    r"^[ \t]*(?:\d{1,2}\s*[-－]\s*\d{1,2}|\d{1,2})\s*\.\s*(\S.{0,50})$", re.M)
_HEADING_BULLET = re.compile(r"^[ \t]*[□■◇◆ㅁ]\s*(\S[^\n]{0,24})$", re.M)
_BULLET_TITLE_MAX = 20      # 공백 지운 제목이 이보다 길면 본문 문장으로 본다


def _heading_hits(text: str) -> list[tuple[int, str]]:
    """제목 줄 위치와 제목 문자열. 두 꼴을 모아 위치순으로 돌려준다."""
    hits: list[tuple[int, str]] = []
    for m in _HEADING_NUM.finditer(text or ""):
        hits.append((m.start(), strip_ws(m.group(1))))
    for m in _HEADING_BULLET.finditer(text or ""):
        t = strip_ws(m.group(1))
        # 쉼표가 있으면 문장이다. 「□ 신청자격」에는 쉼표가 없다.
        if len(t) <= _BULLET_TITLE_MAX and "," not in t:
            hits.append((m.start(), t))
    hits.sort()
    return hits


# 목차 판별. 목차는 제목이 촘촘히 붙어 있고 문서 앞머리에 있다.
_TOC_GAP = 80        # 제목 사이가 이보다 좁으면 본문이 아니라 목차 줄로 본다
_TOC_MIN_RUN = 4     # 그런 줄이 이만큼 이어지면 목차다
_TOC_HEAD_ZONE = 0.15  # 문서 앞 15% 안에서 시작할 때만 목차로 본다


def sections(text: str) -> list[tuple[int, int, str]]:
    """절 제목으로 구역 구간을 만든다. (시작, 끝, 구역명).

    ⚠ **목차를 버려야 한다.** 실측 IRIS 공고(30,322자)는 앞머리 187~527 위치에 목차가
      있고, 같은 제목이 본문에서 다시 나온다.

    ⚠⚠ 처음엔 「같은 이름이면 가장 긴 구간만 남긴다」로 목차를 걸렀는데 **틀렸다.**
        실측에서 「4.  지원분야 및 신청자격 등」(10191)과 「4-2.  신청자격」(13734)이
        둘 다 신청자격으로 잡히고, 긴 쪽(3543자)이 이겨서 **진짜 신청자격 구간
        13734~14243(509자)이 버려졌다.** 연구소 보유 필수 조항이 바로 그 안(13960)에
        있어서, 게이트가 통째로 안 걸렸다.
        → 목차는 **촘촘함으로** 걸러내고, 같은 이름의 구간은 **이어 붙인다.**
    """
    heads: list[tuple[int, str]] = []
    for pos, title in _heading_hits(text):
        for name, pat in _SECTION_PATTERNS:
            if pat.search(title):
                heads.append((pos, name))
                break
    if not heads:
        return []

    # ── 목차 덩어리 걷어내기 ────────────────────────────────────────────────
    n = len(text or "") or 1
    버릴것: set[int] = set()
    i = 0
    while i < len(heads):
        j = i
        while j + 1 < len(heads) and (heads[j + 1][0] - heads[j][0]) < _TOC_GAP:
            j += 1
        if (j - i + 1) >= _TOC_MIN_RUN and (heads[i][0] / n) <= _TOC_HEAD_ZONE:
            버릴것.update(range(i, j + 1))
        i = j + 1
    heads = [h for k, h in enumerate(heads) if k not in 버릴것]
    if not heads:
        return []

    # ── 구간 만들고, 같은 이름이 잇달으면 합친다 ────────────────────────────
    spans: list[tuple[int, int, str]] = []
    for k, (pos, name) in enumerate(heads):
        end = heads[k + 1][0] if k + 1 < len(heads) else len(text or "")
        if spans and spans[-1][2] == name and spans[-1][1] == pos:
            spans[-1] = (spans[-1][0], end, name)   # 상위 제목 + 하위 제목을 한 구역으로
        else:
            spans.append((pos, end, name))
    return spans


def tag_sections(cs: list[Chunk], spans: list[tuple[int, int, str]]) -> None:
    for c in cs:
        for a, b, name in spans:
            if a <= c.시작 < b:
                c.구역 = name
                break


