# 지원사업이라 우리도 대상이다(공고 66·109).
_교육행사 = ("교육생", "수강생", "세미나", "포럼", "컨퍼런스", "공모전", "경진대회",
             "우수사례", "포상", "표창", "유공", "상담회", "밋업", "데모데이",
             "설명회", "간담회", "워크숍", "워크샵", "체험단", "서포터즈")

# 시·군 단위 지역 제한 — 우리 소재지는 「전남광주 장성군」이다. 지역코드는 광역까지만
# 있어서 해남군·광양시·여수시·진도군·구미시 공고가 그대로 통과하고 있었다(직접 훑어
# 찾음, 2026-09-04). 사업명에 다른 시·군·구가 박혀 있으면 그 지자체 사업이다.
#
# ⚠ 「도시」로 끝나는 말(스마트도시·혁신도시)과 「시장」류를 제외한다. 한글 뒤에 바로
#   한글이 오면(시장·시설·시스템) 지자체명이 아니다 — 부정 전방탐색으로 막는다.
_시군구 = re.compile(r"([가-힣]{2,3})(시|군|구)(?![가-힣])")
_시군_제외 = {"도시", "광역시", "특별시", "특례시", "자치구", "행정구", "산업단지구"}


def _tokens(*texts: str | None) -> set[str]:
    out: set[str] = set()
    for t in texts:
        if not t:
            continue
        t = unicodedata.normalize("NFKC", t).lower()
        for w in re.split(r"[^0-9A-Za-z가-힣]+", t):
            if len(w) >= 2 and w not in _STOP:
                out.add(w)
    return out


def 업종_어휘(company: dict[str, Any]) -> set[str]:
    """회사 업종명·주요제품에서 매칭 어휘를 만든다. 동의어로 조금만 넓힌다."""
    base = _tokens(*(company.get("업종명") or []), company.get("주요제품"))
    out = set(base)
    for w in base:
        for k, syns in _SYNONYM.items():
            if k in w or w in k:
                out.update(syns)
    return {w for w in out if len(w) >= 2}


def industry_features(ann: dict[str, Any], company: dict[str, Any]) -> list[Feature]:
    """공고 제목·요약·지원분야가 우리 업종 어휘와 겹치는 정도.

    근거로 **어느 낱말이 어디서 겹쳤는지**를 남긴다. 「업종이 맞습니다」만 쓰면
    그건 근거가 아니다.
    """
    vocab = 업종_어휘(company)
    haystack = unicodedata.normalize(
        "NFKC",
        " ".join(str(ann.get(k) or "") for k in ("사업명", "요약", "지원분야", "지원대상")),
    ).lower()

    hits = sorted({w for w in vocab if w in haystack})
    out: list[Feature] = []
    if hits:
        out.append(Feature(
            특징키="업종적합도", 종류="가산", 규칙id="M-INDUSTRY", 규칙신뢰도=0.80,
            추출원="메타", 구역="메타", 값_수치=float(len(hits)),
            값_텍스트=", ".join(hits),
            근거문장=f"공고 제목·요약에 우리 업종 어휘 {len(hits)}개가 겹친다: {', '.join(hits)}",
        ))

    rnd = sorted({w for w in _RND_WORDS if w in haystack})
    if rnd:
        out.append(Feature(
            특징키="지원분야_기술", 종류="가산", 규칙id="M-RND-WORD", 규칙신뢰도=0.75,
            추출원="메타", 구역="메타", 값_텍스트=", ".join(rnd),
            근거문장=f"공고 제목·요약이 기술개발 성격이다: {', '.join(rnd)}",
        ))

    # 업종 상충 — 공고 주제가 **우리와 배타적인 산업**인데 우리 업종 어휘는 하나도 안 겹친다.
    #
    # 사용자 지적(2026-09-04): "왜 자꾸 농촌, 식품 이런게 남아있는거냐". 회사 프로필의
    # 업종은 제대로 들어 있었다(이차전지 소재·전지 부품소재 제조 · 리튬이온전지용 분리막).
    # 문제는 업종적합도가 **가산점**이라 안 겹쳐도 감점이 없다는 것이었다 — 그래서 농특산품
    # 박람회가 「확인필요」로 계속 남았다.
    #
    # 「안 겹친다」만으로는 불가로 못 쓴다(예: "스마트공장 지원"엔 우리 어휘가 없지만 우리가
    # 할 수 있다). 그래서 **다른 산업을 명시**하는 경우만 건다 — 그건 "모른다"가 아니라
    # "다르다"다. 실측(2026-09-04): 이 조건에 걸린 것이 확인필요 15건이고 그중 오탐 없음,
    # **「가능」 18건은 하나도 안 걸렸다.** 재보고 넣었다.
    # ⚠ 상충 판정은 **제목·지원분야만** 본다. 요약(긴 본문)까지 넣으면 우연히 걸린다 —
    #   수출 공고에 「출판」, R&D 인력 공고에 「축제」, 동행교육에 「보험」이 스쳐 지나가는
    #   것을 실측했다(2026-09-04). 사업의 주제는 제목에 있다.
    제목 = unicodedata.normalize(
        "NFKC", " ".join(str(ann.get(k) or "") for k in ("사업명", "지원분야"))).lower()

    # 상충을 끄는 근거도 **제목에서** 찾는다. 요약에 「소재」 한 낱말이 스쳤다고 게이트를
    # 끄면 문화예술·농촌 공고가 그대로 통과한다(실측: 169·242 가 그래서 「가능」이었다).
    제목_우리어휘 = sorted({w for w in vocab if w not in _약한어휘 and w in 제목})
    if not 제목_우리어휘:
        상충 = sorted({w for w in _배타업종 if w in 제목})
        if 상충:
            도메인 = sorted({_배타도메인[w] for w in 상충})
            out.append(Feature(
                특징키="업종상충", 종류="게이트", 규칙id="M-INDUSTRY-CONFLICT", 규칙신뢰도=0.85,
                추출원="메타", 구역="메타", 값_텍스트=", ".join(도메인),
                근거문장=f"공고 제목이 「{', '.join(상충)}」({', '.join(도메인)}) 분야다 — "
                        f"우리 업종({', '.join((company.get('업종명') or ['?'])[:2])})과 한 낱말도 겹치지 않는다",
            ))

    # 창업 전용 프로그램 — 업력이 상한을 넘으면 대상이 아니다. 설립일을 알 때만 확정한다.
    # ⚠ 띄어쓰기를 지운 사본에도 대본다 — "창업 공간"·"창업 클리닉"·"창업 협력공간"이
    #   붙여쓴 패턴과 안 맞아 그냥 통과하고 있었다(직접 훑어 찾음, 2026-09-04).
    제목_붙임 = strip_ws(제목)
    창업말 = sorted({w for w in _창업전용 if w in 제목 or w in 제목_붙임})
    if not 창업말 and not any(x in 제목 for x in _창업_예외):
        창업말 = sorted({w for w in _창업_넓은말 if w in 제목})
    설립일 = company.get("설립일")
    if 창업말 and 설립일:
        try:
            업력 = (_today() - _date(설립일)).days / 365.25
        except Exception:
            업력 = None
        if 업력 is not None and 업력 > _창업면제_업력:
            out.append(Feature(
                특징키="창업전용프로그램", 종류="게이트", 규칙id="M-STARTUP-ONLY", 규칙신뢰도=0.85,
                추출원="메타", 구역="메타", 값_텍스트=", ".join(창업말), 값_수치=round(업력, 1),
                근거문장=f"공고 제목이 창업 대상 프로그램이다(「{', '.join(창업말)}」) — "
                        f"우리는 {설립일} 설립 {업력:.0f}년차라 대상이 아니다",
            ))

    # 교육·행사 성격 — 지원금 신청이 아니라 사람을 모으는 자리다.
    행사말 = sorted({w for w in _교육행사 if w in 제목 or w in 제목_붙임})
    if 행사말:
        out.append(Feature(
            특징키="행사공지_교육", 종류="정보", 규칙id="M-EVENT-WORD", 규칙신뢰도=0.80,
            추출원="메타", 구역="메타", 값_텍스트=", ".join(행사말),
            근거문장=f"공고 제목이 교육·행사다(「{', '.join(행사말)}」) — 지원금 신청이 아니다",
        ))

    # 시·군 단위 지역 제한 — 사업명에 다른 지자체가 박혀 있으면 그 지자체 사업이다.
    # 광역(지역코드)만 보던 기존 게이트가 못 잡던 자리다.
    우리시군 = {m.group(0) for m in _시군구.finditer(str(company.get("소재지") or ""))}
    공고시군 = {m.group(0) for m in _시군구.finditer(str(ann.get("사업명") or ""))}
    공고시군 = {s for s in 공고시군 if s not in _시군_제외 and not s.endswith("도시")}
    if 공고시군 and 우리시군 and not (공고시군 & 우리시군):
        out.append(Feature(
            특징키="지역제한_시군", 종류="게이트", 규칙id="M-REGION-CITY", 규칙신뢰도=0.85,
            추출원="메타", 구역="메타", 값_텍스트=", ".join(sorted(공고시군)),
            근거문장=f"사업명이 「{', '.join(sorted(공고시군))}」 사업이다 — "
                    f"우리 소재지는 {company.get('소재지')}다",
        ))
    return out


