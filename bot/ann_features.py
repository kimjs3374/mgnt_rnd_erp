# 글머리표. 공고문은 문장이 아니라 이 기호 단위로 읽힌다.
_BULLET = re.compile(
    r"^[ \t]*("
    r"[ㅇㅁ○●◦◯□■◇◆▪▫▶►·※*☞]"          # 한글 공고문에서 실제로 쓰이는 것들. ☞ 는 기업마당 요약 전용
    r"|[①-⑳]|[㉠-㉻]|[⒈-⒛]"
    r"|\(?\d{1,2}\)"                        # (1) 1)
    r"|\d{1,2}\s*-\s*\d{1,2}\s*\."          # 4-2.
    r"|\d{1,2}\s*\."                        # 1.
    r"|[가-하]\s*\."                        # 가.
    r"|[-–—]\s"                             # 줄 맨 앞의 하이픈만. 「제 2026 – 40 호」에 걸리지 않게 한다
    r")"
)


# API 요약(예: 기업마당 pbanc_ctnt)은 줄바꿈이 하나도 없이 통짜 한 줄로 온다(실측 확인:
# length(요약) 300자대인데 줄바꿈 0개). chunks() 는 줄 시작에서만 글머리를 인식하므로
# 그대로 두면 전체가 한 덩어리가 되어 "☞ 도내 소재 자동차부품 제조 중소기업" 같은
# 자격요건 문장이 앞뒤 홍보 문구에 묻혀 규칙이 못 본다. 글머리 기호 앞에 줄바꿈을 넣어
# 준다 — HWP·PDF 에서 뽑은 진짜 본문(이미 줄바꿈이 있다)에는 건드릴 필요가 없다.
_INLINE_BULLET_CHARS = "☞ㅇㅁ○●◦◯□■◇◆▪▫▶►※"


def _linebreak_bullets(text: str) -> str:
    out: list[str] = []
    for i, ch in enumerate(text):
        if i > 0 and ch in _INLINE_BULLET_CHARS and text[i - 1] != "\n":
            out.append("\n")
        out.append(ch)
    return "".join(out)


def strip_ws(s: str) -> str:
    """공백을 모두 지운 사본. **매칭 전용이다.**

    추출물이 「부채비율이 연속  500%  이상」처럼 벌어져 온다. 공백 위치가 제각각이라
    패턴에 `\\s*` 를 흩뿌리면 읽을 수 없고 빠뜨리기도 한다. 한국어는 정규식 매칭에
    공백이 필요 없으니 아예 지우고 맞춘다. 표시·인용은 항상 원문 쪽을 쓴다.
    """
    return re.sub(r"\s+", "", s or "")


def tidy(s: str, limit: int = 400) -> str:
    """인용용으로 공백만 접는다. **글자는 하나도 바꾸지 않는다.**

    추출물의 공백이 원문 조판이 아니라 파서 산물이라 그대로 두면 화면에서 읽히지 않는다.
    원문 어디였는지는 Feature.근거_위치 로 남으니 원문 대조가 그대로 가능하다.
    """
    t = re.sub(r"\s+", " ", (s or "")).strip()
    return t if len(t) <= limit else t[:limit].rstrip() + "…"


@dataclass
class Chunk:
    """글머리표 하나 분량의 덩어리. 근거문장의 단위다."""
    원문: str
    시작: int
    flat: str = field(default="", repr=False)
    구역: str | None = None

    def __post_init__(self) -> None:
        if not self.flat:
            self.flat = strip_ws(self.원문)


def chunks(text: str) -> list[Chunk]:
    """본문을 글머리표 단위로 쪼갠다. 이어지는 줄은 앞 덩어리에 붙인다.

    ⚠ 한 줄 단위로 쪼개면 안 된다. 실측 본문이 이렇게 끊겨 있다:
        「◦ 주관연구개발기관이 기업인 경우는 접수마감일 현재 법인사업자이어야 하며, 선정
          평가 개최일 이전에 기업부설연구소 (…) 를 보유
          하고 있어야 함」
      「보유하고 있어야 함」이 세 줄에 걸쳐 있어서, 줄 단위로 보면 조건을 못 읽는다.
    """
    out: list[Chunk] = []
    buf: list[str] = []
    start = 0
    pos = 0

    def flush() -> None:
        nonlocal buf, start
        if buf:
            raw = "".join(buf)
            if strip_ws(raw):
                out.append(Chunk(원문=raw, 시작=start))
        buf = []

    for line in (text or "").splitlines(keepends=True):
        bare = line.strip()
        if not bare:                      # 빈 줄은 덩어리 경계다
            flush()
            pos += len(line)
            start = pos
            continue
        if _BULLET.match(line) and buf:   # 새 글머리표 → 앞 덩어리를 끊는다
            flush()
            start = pos
        if not buf:
            start = pos
        buf.append(line)
        pos += len(line)
    flush()
    return out


