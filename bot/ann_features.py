# 렉시콘 — 사람 정정에서 배운 패턴. 정규식보다 **먼저** 본다
# ─────────────────────────────────────────────────────────────────────────────
def scan_lexicon(cs: list[Chunk], lexicon: list[dict] | None) -> list[Feature]:
    """app.extraction_lexicon 행을 적용한다.

    이 함수가 「쌓으면 LLM 없이도 판단이 된다」의 실제 경로다. 사람이 짚어준 문구가
    행으로 쌓이면, 다음 판독은 정규식이 못 뽑은 것을 여기서 뽑는다.
    벡터 DB 를 넣지 않는다(CLAUDE.md §7) — 부분문자열·정규식으로 충분하다.
    """
    out: list[Feature] = []
    for lx in lexicon or []:
        if not lx.get("사용중", True):
            continue
        패턴 = strip_ws(str(lx.get("패턴") or ""))
        if not 패턴:
            continue
        구역 = lx.get("구역")
        정규식 = str(lx.get("패턴유형") or "") == "정규식"
        for c in cs:
            if 구역 and c.구역 != 구역:
                continue
            hit = re.search(패턴, c.flat) if 정규식 else (패턴 in c.flat)
            if not hit:
                continue
            out.append(Feature(
                특징키=str(lx["특징키"]),
                종류=str(lx.get("종류") or "정보"),
                규칙id=f"LX-{lx.get('id')}",
                규칙신뢰도=float(lx.get("신뢰도") or 0.9),
                추출원="렉시콘",
                근거문장=tidy(c.원문),
                근거_위치=c.시작,
                구역=c.구역,
                값_텍스트=lx.get("값_텍스트"),
                값_수치=lx.get("값_수치"),
                값_불리언=lx.get("값_불리언"),
            ))
            break
    return out


