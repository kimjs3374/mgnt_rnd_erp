# 규칙 — 전부 실제 본문에서 확인한 문구로 만들었다
#
# 각 규칙의 `sections` 는 「이 구역에서만 본다」는 뜻이다. None 이면 어디서든.
# `conf` 는 패턴이 얼마나 특정적인가다 — 사람 확인으로 갱신될 자리다.
#   0.90+ 문구가 조건을 직접 말한다 · 0.80 문맥에 거의 의존하지 않는다
#   0.70  예외 조항에 걸릴 수 있다(단서·「예외로 한다」 안에도 같은 문구가 있다)
# ─────────────────────────────────────────────────────────────────────────────
@dataclass
class Rule:
    id: str
    특징키: str
    종류: str
    pattern: re.Pattern[str]
    conf: float
    sections: tuple[str, ...] | None = None
    단위: str | None = None
    수치그룹: int | None = None       # 숫자를 뽑을 캡처 그룹
    값불리언: bool | None = None      # 조항이 있으면 이 값으로 둔다
    금지_후행: re.Pattern[str] | None = None   # 매치 직후에 이게 나오면 버린다
    구역없어도: bool = False          # 구역을 못 갈랐을 때도 볼 것인가
    설명: str = ""

    def scan(self, cs: list[Chunk]) -> Iterable[Feature]:
        for c in cs:
            깎기 = 1.0
            if self.sections is not None and c.구역 not in self.sections:
                # 구역을 아예 못 갈랐으면(=문서에 절 제목이 없다) 조건절이 자기 뜻을
                # 스스로 말하는 규칙만 예외로 본다. 신뢰도를 낮춰 그 사실을 남긴다.
                if not (self.구역없어도 and c.구역 is None):
                    continue
                깎기 = 0.85
            m = self.pattern.search(c.flat)
            if not m:
                continue
            # 단서·예외 조항 안의 문구를 조건으로 오해하지 않는다. 실측:
            #   「…사업개시일로부터 접수마감일까지 5년 미만인 기업의 경우는 적용하지 아니한다」
            # 를 업력 조건으로 잡아 엉뚱한 확인필요를 만들었다.
            if self.금지_후행 and self.금지_후행.search(c.flat[m.end():m.end() + 30]):
                continue
            num = None
            if self.수치그룹 is not None:
                try:
                    num = float(m.group(self.수치그룹).replace(",", ""))
                except (IndexError, ValueError, AttributeError):
                    num = None
            yield Feature(
                특징키=self.특징키,
                종류=self.종류,
                규칙id=self.id,
                규칙신뢰도=round(self.conf * 깎기, 3),
                추출원="본문",
                근거문장=tidy(c.원문),
                근거_위치=c.시작,
                구역=c.구역 or "미상",
                값_텍스트=m.group(0)[:200],
                값_수치=num,
                값_불리언=self.값불리언,
                단위=self.단위,
            )
            return    # 규칙당 한 건. 같은 조항이 문서에 반복돼도 특징은 하나다


