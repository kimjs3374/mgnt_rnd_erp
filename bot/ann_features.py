_SYNONYM = {
    "이차전지": ("이차전지", "2차전지", "배터리", "전지"),
    "전지": ("전지", "배터리", "이차전지"),
    "분리막": ("분리막", "세퍼레이터", "separator"),
    "소재": ("소재", "재료", "부품", "소부장", "소재부품장비"),
    "부품": ("부품", "소재", "소부장"),
}

# R&D 성격 어휘. 지원분야 패싯이 「기술」이 아닐 때도 사업명에서 잡힌다.
_RND_WORDS = ("기술개발", "연구개발", "r&d", "rnd", "시제품", "실증", "고도화",
              "기술사업화", "특허", "지식재산", "기술이전", "산학연")


def _tokens(*texts: str | None) -> set[str]:
    out: set[str] = set()
    for t in texts:
        if not t:
            continue
        t = unicodedata.normalize("NFKC", t).lower()
        for w in re.split(r"[^0-9A-Za-z가-힣]+", t):
            if len(w) >= 2 and w not in _STOP:
                out.add(w)
    return out


def 업종_어휘(company: dict[str, Any]) -> set[str]:
    """회사 업종명·주요제품에서 매칭 어휘를 만든다. 동의어로 조금만 넓힌다."""
    base = _tokens(*(company.get("업종명") or []), company.get("주요제품"))
    out = set(base)
    for w in base:
        for k, syns in _SYNONYM.items():
            if k in w or w in k:
                out.update(syns)
    return {w for w in out if len(w) >= 2}


def industry_features(ann: dict[str, Any], company: dict[str, Any]) -> list[Feature]:
    """공고 제목·요약·지원분야가 우리 업종 어휘와 겹치는 정도.

    근거로 **어느 낱말이 어디서 겹쳤는지**를 남긴다. 「업종이 맞습니다」만 쓰면
    그건 근거가 아니다.
    """
    vocab = 업종_어휘(company)
    haystack = unicodedata.normalize(
        "NFKC",
        " ".join(str(ann.get(k) or "") for k in ("사업명", "요약", "지원분야", "지원대상")),
    ).lower()

    hits = sorted({w for w in vocab if w in haystack})
    out: list[Feature] = []
    if hits:
        out.append(Feature(
            특징키="업종적합도", 종류="가산", 규칙id="M-INDUSTRY", 규칙신뢰도=0.80,
            추출원="메타", 구역="메타", 값_수치=float(len(hits)),
            값_텍스트=", ".join(hits),
            근거문장=f"공고 제목·요약에 우리 업종 어휘 {len(hits)}개가 겹친다: {', '.join(hits)}",
        ))

    rnd = sorted({w for w in _RND_WORDS if w in haystack})
    if rnd:
        out.append(Feature(
            특징키="지원분야_기술", 종류="가산", 규칙id="M-RND-WORD", 규칙신뢰도=0.75,
            추출원="메타", 구역="메타", 값_텍스트=", ".join(rnd),
            근거문장=f"공고 제목·요약이 기술개발 성격이다: {', '.join(rnd)}",
        ))
    return out


