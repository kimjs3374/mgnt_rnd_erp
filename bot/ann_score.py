# 판정
# ─────────────────────────────────────────────────────────────────────────────
def _학습판정(과거판정: list[dict] | None) -> dict[str, Any] | None:
    """과거 사람 판정에서 **같은 특징키로 여러 건이 같은 결론**인 것만 골라 돌려준다.

    입력은 semantic_learn.find_similar() 의 결과다 — 이 함수는 DB 도 모델도 안 부른다
    (judge() 의 순수성을 지킨다. 조회는 부르는 쪽(ann_rules.py)이 한다).

    돌려주는 것이 없으면 None — 학습이 할 말이 없다는 뜻이지 「가능」이라는 뜻이 아니다.
    """
    if not 과거판정:
        return None
    묶음: dict[str, list[dict]] = {}
    for m in 과거판정:
        키 = (m.get("특징키") or "").strip()
        if not 키 or float(m.get("유사도") or 0) < LEARN_MIN_SIM:
            continue          # 특징키가 없으면 "무엇 때문에 불가인지"를 못 적는다 — 안 쓴다
        묶음.setdefault(키, []).append(m)

    for 키, 사례들 in sorted(묶음.items(), key=lambda kv: -max(x["유사도"] for x in kv[1])):
        판정들 = {x.get("판정") for x in 사례들}
        if len(사례들) < LEARN_MIN_CASES or len(판정들) != 1:
            continue          # 결론이 갈리면 사람이 봐야 한다 — 대신 정하지 않는다
        판정 = 판정들.pop()
        if 판정 not in LEARN_VERDICTS:
            continue
        return {
            "특징키": 키,
            "판정": 판정,
            "유사도": max(x["유사도"] for x in 사례들),
            "사례": [
                {"공고": x.get("announcement_id"), "유사도": x["유사도"],
                 "텍스트": x.get("텍스트"), "사유": x.get("사유"), "답변자": x.get("답변자")}
                for x in sorted(사례들, key=lambda x: -x["유사도"])
            ],
        }
    return None


def judge(ann: dict, company: dict, weights: list[dict] | None = None,
          lexicon: list[dict] | None = None,
          과거판정: list[dict] | None = None) -> dict[str, Any]:
    """공고 한 건을 판정한다. **순수 함수다** — DB 를 만지지 않고 LLM 을 부르지 않는다.

    순수하게 둔 이유: 테스트가 DB 없이 돌아야 하고, 게이트웨이·MCP·배치가 같은 함수를
    부를 수 있어야 한다. gongo.py 프롬프트가 두 벌이 됐던 사고를 되풀이하지 않는다.
    """
    w = {r["특징키"]: float(r.get("가중치") or 0) for r in (weights or [])}
    회사컬럼 = {r["특징키"]: r["회사컬럼"] for r in (weights or []) if r.get("회사컬럼")}
    if not w:
        # 가중치 표를 못 읽었으면 점수를 매기지 않는다. 0 으로 매기면 전부 「불가」처럼 보인다.
        return {"ok": False, "error": "scoring_weights 를 읽지 못했다. 점수를 매기지 않는다."}

    ext = F.extract(ann, company, lexicon=lexicon)
    feats: list[F.Feature] = ext["features"]

    # 사용자 지적(2026-09-04): 이벤트 공지는 게이트·점수를 매기기 전에 먼저 걸러낸다.
    # "일시:…장소:"(단발성 행사 구조) 하나만으로도 충분히 특정적이다(실측 확인) — 그게
    # 없으면 "무료"와 "제한없음" 둘 다 있어야 한다(하나만으론 진짜 지원사업 문구에도
    # 우연히 나올 수 있다). 자격 문제가 아니므로 게이트·확인필요를 거치지 않는다 —
    # ann_rule_scores.chk_rule_판정 을 db/106_event_notice.sql 로 넓혀 이 값을 받는다.
    #
    # ⚠ 실측 버그(2026-09-04, 사용자 지적: 공고 488 "네트워킹 강연인데 걸러내지를 못하고"):
    #   여기서 찾던 "행사공지_일시장소"는 **어느 규칙도 만들지 않는 키였다.** 추출 쪽
    #   (ann_features.py)은 R-EVENT-DATETIME → "행사공지_일시", R-EVENT-LOCATION →
    #   "행사공지_장소"로 따로 넣는데 판정 쪽만 합친 이름을 보고 있었다. 그래서 주 조건이
    #   죽은 코드였고, 대체 조건(무료+제한없음)은 실측 0건 — **행사 감지가 여태 한 건도
    #   안 걸렸다.** 일시·장소 둘 다 있는 공고가 36건 있었는데 전부 통과했다.
    #
    # 여기에 하나 더 — 오픈API 가 지원분야에 「행사ㆍ네트워크」라고 **직접 알려주는** 공고가
    #   150건이다. 본문을 파싱할 필요도 없는 계산 자리다(설계원칙 1). 주최 측이 스스로
    #   분류한 값이라 본문 정규식보다 세다.
    #
    # 오픈API 의 지원분야로 거른다. 주최 측이 스스로 붙인 분류라 본문 정규식보다 세다.
    #
    # ⚠ 「멘토링ㆍ컨설팅ㆍ교육」을 처음엔 뺐었다 — "우리가 「가능」으로 판정한 254(글로벌
    #   기술도입 전문가 컨설팅지원)가 그 분야라 같이 걸면 기회를 죽인다"고 적었는데,
    #   **그 근거가 틀렸다.** 실제로 254 의 지원분야는 「기술」이다(실측, 2026-09-04).
    #   틀린 근거로 만든 예외 때문에 컨설팅·교육 공고가 그대로 새고 있었다
    #   (사용자 지적: 483 취약분야 상시 컨설팅 · 354 디캠프 배치 · 364 SaaS 교육).
    #   그 분야에 남아 있던 5건을 다시 읽어보니 우리와 관계있는 것이 하나도 없다.
    #
    # 「시설ㆍ공간ㆍ보육」도 넣는다 — 입주공간·보육센터 제공이다. 우리는 장성군에 공장이
    #   있는 21년차 제조사라 입주 대상이 아니다(실측: 남아 있던 7건 전부 대학·센터 입주).
    행사키 = {f.특징키 for f in feats if f.특징키.startswith("행사공지_")}
    지원분야 = str(ann.get("지원분야") or "")
    분야가행사 = any(w in 지원분야 for w in
                     ("행사", "네트워크", "창업교육", "멘토링", "컨설팅", "교육",
                      "시설", "공간", "보육"))
    if (분야가행사
            or "행사공지_교육" in 행사키          # 제목이 교육생 모집·세미나·공모전·포상류다
            or {"행사공지_일시", "행사공지_장소"} <= 행사키
            or {"행사공지_무료", "행사공지_제한없음"} <= 행사키):
        행사근거 = [f.근거문장 for f in feats if f.특징키.startswith("행사공지_")]
        if 분야가행사:
            행사근거.insert(0, f"공고가 스스로 밝힌 지원분야가 「{지원분야}」다")
        return {
            "ok": True, "엔진버전": F.ENGINE_VERSION, "점수": 0, "판정": "해당없음",
            "확신도": 0.85, "커버리지": 1.0 if ext.get("본문사용") else 0.0,
            "커버리지_상세": {"메타": 0.0, "본문": 1.0 if ext.get("본문사용") else 0.0},
            "판정경로": "규칙", "llm_호출": 0,
            "게이트_결과": [], "특징_기여": [], "확인필요항목": [], "확인필요_상세": [],
            "근거": ["지원금 신청이 아니라 무료 행사·교육 공지로 읽힌다 — 자격 판정 대상이 아니다"]
                    + 행사근거,
            "features": feats, "본문사용": ext["본문사용"], "본문길이": ext["본문길이"],
            "구역": ext["구역"], "제출서류": [],
        }

    게이트 = _gates(ann, company, feats)
    기여 = _가산(ann, company, feats, w)
    확인 = _확인필요(company, feats, 회사컬럼)
    커버리지, meta축, body축 = _커버리지(feats, ext["본문사용"])

    # 보류 게이트는 「어긋나 보이지만 확정하지 않는다」 — 불가로 죽이지 않고 사람에게 묻는다
    for g in 게이트:
        if g.get("보류") and not g["통과"]:
            확인.append({"특징키": g["키"], "사유": g["사유"],
                         "근거문장": g["근거"], "필요값": None})

    위반 = [g for g in 게이트 if not g["통과"] and not g.get("보류")]
    점수 = BASE_SCORE + sum(c["점수"] for c in 기여)
    점수 = int(round(max(0.0, min(100.0, 점수))))

    근거: list[str] = []
    학습 = _학습판정(과거판정)

    # ── 판정 순서. 위에서 걸리면 아래는 보지 않는다 ──────────────────────────
    if 위반:
        # 게이트는 계산이다. 본문이 없어도 여기서 확정한다 —
        # 마감 지난 공고를 「요건미확인」으로 두면 목록이 쓰레기가 된다.
        판정 = "불가"
        점수 = min(점수, GATE_FAIL_MAX)
        확신도 = max(g["신뢰도"] for g in 위반)
        근거 = [f"{g['키']}: {g['사유']}" for g in 위반]
    elif 학습:
        # 규칙이 확정하지 못한 자리에서 **사람이 이미 내린 같은 결론**을 쓴다.
        # 계산으로 확정되는 게이트(위)보다는 약하고, 커버리지 부족(아래)보다는 세다 —
        # "못 읽었다"고 손 놓기 전에 "전에 사람이 뭐라 했는지"를 먼저 본다.
        # 확신도는 유사도 그대로 둔다(0.70 자동확정선 아래라 사람 확인 대상으로 남는다) —
        # 유사도는 증거가 아니라 정황이라는 뜻을 숫자로도 남긴다.
        판정 = 학습["판정"]
        점수 = min(점수, GATE_FAIL_MAX)
        확신도 = round(float(학습["유사도"]), 3)
        근거 = [f"과거 유사 판정 {len(학습['사례'])}건이 모두 「{학습['판정']}」 "
                f"— {학습['특징키']} (유사도 {학습['유사도']:.2f})"]
        근거 += [f"  · [{c['공고']}] \"{(c['텍스트'] or '')[:60]}\""
                 + (f" — {c['사유']}" if c.get("사유") else "")
                 + f" ({c['답변자']}, 유사도 {c['유사도']:.2f})"
                 for c in 학습["사례"]]
    elif 커버리지 < MIN_COVERAGE:
        # 조항을 못 읽었다. 「불가」로 찍으면 그 공고는 조용히 버려진다(§6 설계 원칙 4번).
        판정 = "요건미확인"
        확신도 = round(커버리지, 3)
        근거 = [f"판정에 필요한 요건을 다 못 읽었다 (커버리지 {커버리지:.2f}"
                f" = 메타 {meta축:.2f}·본문 {body축:.2f})"]
        근거 += ([f"본문이 {ext['본문길이']}자뿐이다 — 공고문 첨부를 받아야 판정된다"]
                 if not ext["본문사용"] else [])
    else:
        평균신뢰 = (sum(f.규칙신뢰도 for f in feats) / len(feats)) if feats else 0.0
        확신도 = round(평균신뢰 * 커버리지, 3)
        근거 = [f"{g['키']}: {g['사유']}" for g in 게이트 if g["통과"]]
        근거 += [f"{c['키']} +{c['점수']:g}점" for c in 기여]

        # 실측 버그(2026-09-04, id 192·193): 보성군 「일반음식점 시설환경개선 지원사업」이
        # 「가능」으로 나왔다 — 게이트(지역·마감·지원대상)는 통과했지만 업종적합도 가산이
        # 0 인 채였다. 공고 원문엔 "일반음식점을 영업 중인 자"라고 못박혀 있어 이차전지
        # 소재 제조업인 우리와 무관하다. 지역·마감·「중소기업」 같은 범용 태그만으로는
        # "이 사업 주제가 우리 업종과 실제로 관련 있다"를 증명하지 못한다 — 그런데
        # 점수는 60점을 넘길 수 있었다(지역_우리지역명시 +7 · 대상_중소기업명시 +5 ·
        # 지원분야_기술 +6 만으로도 넘는다). 업종 근거가 하나도 없이 「가능」을 내지 않는다.
        업종근거있음 = any(c["키"] == "업종적합도" for c in 기여)

        if 확인:
            # PROMPT_SCORE 규칙 4 — 점수가 높아도 모르는 게 있으면 「가능」이라 하지 않는다
            판정 = "확인필요"
            확신도 = min(확신도, UNKNOWN_CONF_CAP)
        elif 점수 >= PASS_SCORE and not 업종근거있음:
            판정 = "확인필요"
            확신도 = min(확신도, UNKNOWN_CONF_CAP)
            근거.append(f"게이트는 통과했고 {점수}점이지만, 우리 업종 어휘와 겹치는 근거가 "
                        f"하나도 없다 — 지역·마감·기업규모만으로는 사업 주제가 맞는지 알 수 없다")
        elif 점수 >= PASS_SCORE:
            판정 = "가능"
        else:
            판정 = "확인필요"
            근거.append(f"게이트는 통과했으나 적합도가 {점수}점으로 {PASS_SCORE}점에 못 미친다")

    return {
        "ok": True,
        "엔진버전": F.ENGINE_VERSION,
        "점수": 점수,
        "판정": 판정,
        "확신도": round(min(1.0, max(0.0, 확신도)), 3),
        "커버리지": 커버리지,
        "커버리지_상세": {"메타": meta축, "본문": body축},
        # 학습이 판정을 바꾼 건은 경로에 남긴다 — 화면·이력에서 "왜 불가인지"를 되짚을 수
        # 있어야 정정도 가능하다. ann_sync_decisions 는 ai_제안.판정경로에 "규칙"을 따로
        # 써 넣으므로(97행) 섀도 대조 뷰(db/105_)는 이 값에 영향받지 않는다.
        "판정경로": "규칙+학습" if 학습 and 판정 == 학습["판정"] and not 위반 else "규칙",
        "학습근거": 학습 if 학습 and 판정 == 학습["판정"] and not 위반 else None,
        "llm_호출": 0,
        "게이트_결과": 게이트,
        "특징_기여": 기여,
        "확인필요항목": [c["특징키"] for c in 확인],
        "확인필요_상세": 확인,
        "근거": 근거,
        "features": feats,
        "본문사용": ext["본문사용"],
        "본문길이": ext["본문길이"],
        "구역": ext["구역"],
        "제출서류": sorted({f.값_텍스트 for f in feats
                            if f.특징키 == "제출서류" and f.값_텍스트}),
    }


