# 「확인해보세요」는 질문이 아니다. **근거문장을 인용하고 무엇을 답해야 하는지**를 준다.
# 답은 app.ann_feature_answers 로 가고, 일반화=true 인 답은 회사 상수로 승격돼
# 다음 공고에서 다시 묻지 않는다.
# ─────────────────────────────────────────────────────────────────────────────
# (질문, 일반화후보). 일반화후보=True 는 「공고와 무관한 회사 사실」이라 한 번 답하면
# 회사 상수가 되고 다음 공고에서 다시 묻지 않는다.
# 체납·참여제한은 시점에 매인 사실이지만 **공고에 매인 사실은 아니다** — 회사 상태다.
# 그래서 일반화 대상으로 두고, 언제 확인한 답인지는 answers.created_at 이 말한다.
질문틀 = {
    # 예/아니오가 아니라 **값**을 묻는다. 답이 숫자로 들어와야 다음 공고의 다른 상한과도
    # 대조된다 — 「이 공고 기준으로는 통과」라는 답은 다음 공고에 쓸 수 없다.
    "부채비율_상한":   ("최근 결산 부채비율이 몇 %입니까? (이 공고 상한은 {값}%)", True),
    "매출액_기준":     ("최근 결산 매출액이 얼마입니까? (원 단위)", True),
    "종업원수_기준":   ("상시 종업원수가 몇 명입니까?", True),
    "업력_제한":       ("법인 설립일이 언제입니까? (공고가 업력 {값}년 조건을 걸었다)", True),
    "자본전액잠식_제외": ("현재 자본전액잠식 상태입니까?", True),
    "체납_제외":       ("국세·지방세 체납이 없습니까? (납세증명서로 확인)", True),
    "참여제한_제외":   ("국가연구개발사업 참여제한을 받고 있지 않습니까?", True),
    "법인사업자_필수": ("법인사업자입니까?", True),
    "기업부설연구소_필수": ("기업부설연구소 인정서를 보유하고 있습니까?", True),
    # 지역 보류는 **이 공고 한정**이다. 일반화하면 다른 지역 공고까지 열려버린다.
    "지역제한":        ("공고 지역이 우리 소재지와 다릅니다. 그래도 신청 가능한 사업입니까? "
                        "(중앙부처 사업이라 지역코드가 수행지역일 수 있습니다)", False),
    "기관유형_제한":   ("대학·연구기관 전용으로 읽혔습니다. 기업이 신청할 수 있는 공고입니까?", False),
}


def questions(result: dict, ann: dict) -> list[dict]:
    """확인필요항목을 사람이 답할 수 있는 질문으로 바꾼다.

    일반화=True 는 「공고와 무관한 회사 사실」이라 한 번 답하면 회사 상수가 된다.
    False 는 시점·공고에 매인 사실이라 공고마다 다시 확인해야 한다(체납·참여제한).
    """
    by키 = {f.특징키: f for f in result.get("features", [])}
    out: list[dict] = []
    for 항목 in result.get("확인필요_상세", []):
        키 = 항목["특징키"]
        틀, 일반화 = 질문틀.get(키, (f"「{키}」 요건을 만족합니까?", False))
        f = by키.get(키)
        값 = f"{f.값_수치:g}" if (f is not None and f.값_수치 is not None) else "?"
        out.append({
            "announcement_id": ann.get("id"),
            "특징키": 키,
            "질문": 틀.replace("{값}", 값),
            "근거문장": 항목.get("근거문장"),
            "ai_추출값": (f.값_텍스트 if f is not None else None),
            "일반화후보": 일반화,
            "필요값": 항목.get("필요값"),
        })
    return out
