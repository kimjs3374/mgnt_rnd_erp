# 확인필요 — 「모르는 것」을 목록으로 만든다. 점수를 깎지 않는다
# ─────────────────────────────────────────────────────────────────────────────
# 우리 DB 에 아예 항목이 없는 사실들. 서류나 사람 답변으로만 확인된다.
# 「인건비·개인정보는 항목 자체를 만들지 않는다」(CLAUDE.md §6)와 같은 성격으로,
