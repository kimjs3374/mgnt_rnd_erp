DB에없는사실 = {
    "체납_제외":     ("국세·지방세 체납 여부 (납세증명서로만 확인된다)", "_체납없음"),
    "참여제한_제외": ("국가연구개발사업 참여제한 여부 (우리 DB 에 없는 사실이다)", "_참여제한없음"),
}


def _확인필요(company: dict, feats: list[F.Feature], 회사컬럼: dict[str, str]) -> list[dict]:
    """확인이 필요한 항목. {특징키, 사유, 근거문장, 필요값}.

    공고가 그 조건을 실제로 걸었을 때만 올린다 — 공고에 없는 조건을 「확인하세요」로
    내밀면 사람이 헛일을 한다.
    """
    out: list[dict] = []
    본: set[str] = set()

    for f in feats:
        if f.특징키 in 본:
            continue

        if f.특징키 in DB에없는사실:
            사유, 칸 = DB에없는사실[f.특징키]
            본.add(f.특징키)
            if company.get(칸) is not None:
                continue          # 사람이 이미 답했다. 같은 것을 다시 묻지 않는다
            out.append({"특징키": f.특징키, "사유": 사유,
                        "근거문장": f.근거문장, "필요값": 칸})
            continue

        컬럼 = 회사컬럼.get(f.특징키)
        if 컬럼 and company.get(컬럼) is None:
            본.add(f.특징키)
            out.append({
                "특징키": f.특징키,
                "사유": f"공고가 이 조건을 걸었는데 회사 정보의 「{컬럼}」이 비어 있다",
                "근거문장": f.근거문장,
                "필요값": 컬럼,
            })

    # 법인사업자 조항은 사업자등록번호로 확정된다 — 확인필요로 올리지 않는다
    if any(f.특징키 == "법인사업자_필수" for f in feats):
        if 법인여부(company.get("사업자등록번호")) is None:
            out.append({"특징키": "법인사업자_필수",
                        "사유": "법인/개인을 가릴 사업자등록번호가 없다",
                        "근거문장": next(f.근거문장 for f in feats if f.특징키 == "법인사업자_필수"),
                        "필요값": "사업자등록번호"})
    return out


