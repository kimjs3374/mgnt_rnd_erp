# 가산 — 게이트를 통과한 공고에 점수를 올린다. 가중치는 DB(scoring_weights)에서 온다
# ─────────────────────────────────────────────────────────────────────────────
def _가산(ann: dict, company: dict, feats: list[F.Feature], w: dict[str, float]) -> list[dict]:
    """특징_기여 목록. {키, 가중치, 점수, 근거}. 합이 50 을 넘지 않게 가중치를 뒀다."""
    by키: dict[str, F.Feature] = {f.특징키: f for f in feats}
    out: list[dict] = []

    def put(키: str, 비율: float, 근거: str) -> None:
        가중 = float(w.get(키, 0))
        if 가중 <= 0:
            return
        out.append({"키": 키, "가중치": 가중, "점수": round(가중 * max(0.0, min(1.0, 비율)), 2),
                    "근거": 근거})

    # 업종적합도 — 겹친 낱말 수. 3개 이상이면 만점으로 본다(그 이상은 더 확실해지지 않는다)
    f = by키.get("업종적합도")
    if f is not None:
        n = int(f.값_수치 or 0)
        put("업종적합도", min(1.0, n / 3.0), f.근거문장)

    # 지원분야 — API 패싯이 기술 계열이면 만점, 제목에서만 잡혔으면 0.6
    f = by키.get("지원분야_기술")
    if f is not None:
        패싯 = (ann.get("지원분야") or "")
        기술패싯 = any(k in 패싯 for k in ("기술", "R&D", "연구"))
        put("지원분야_기술", 1.0 if 기술패싯 else 0.6, f.근거문장)

    # 연구소 — 공고가 요구하거나 가점을 주고, 우리가 보유한 경우
    if by키.get("연구소_보유가점") is not None and company.get("기업부설연구소"):
        put("연구소_보유가점", 1.0,
            by키["연구소_보유가점"].근거문장 + " / 우리 기업부설연구소 보유")

    # 지역 — 「전국」이 아니라 우리 지역을 콕 집은 공고. 경쟁 모수가 작다
    공고지역 = set(ann.get("지역코드") or [])
    우리지역 = set(company.get("지역코드") or [])
    맞은지역 = 지역겹침(공고지역, 우리지역)
    if 맞은지역 and "전국" not in 공고지역:
        put("지역_우리지역명시", 1.0, f"공고가 우리 지역({'·'.join(sorted(맞은지역))})을 지정했다")

    # 지원대상에 중소기업이 명시
    대상 = (ann.get("지원대상") or "")
    if "중소기업" in 대상 or by키.get("대상_중소기업명시") is not None:
        근거 = (by키["대상_중소기업명시"].근거문장 if by키.get("대상_중소기업명시")
                else f"공고 지원대상 「{대상}」")
        put("대상_중소기업명시", 1.0, 근거)

    return out


