    찬것 = sum(1 for k in ("접수마감", "지역제한", "지원대상_유형") if k in 있는키)
    if {"업종적합도", "지원분야_기술"} & 있는키:      # 사업성격 자리
        찬것 += 1
    meta = 찬것 / 4.0

    본문특징 = [f for f in feats if f.추출원 in ("본문", "렉시콘") and f.특징키 != "제출서류"]
    body = min(1.0, len(본문특징) / BODY_TARGET) if 본문사용 else 0.0

    return (round(META_WEIGHT * meta + (1 - META_WEIGHT) * body, 3),
            round(meta, 3), round(body, 3))


