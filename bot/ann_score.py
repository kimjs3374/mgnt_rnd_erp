def 법인여부(brn: str | None) -> bool | None:
    """사업자등록번호로 법인/개인을 가른다. 형식이 아니면 None(모른다)."""
    digits = re.sub(r"\D", "", brn or "")
    if len(digits) != 10:
        return None
    return digits[3:5] in 법인_코드


def _today() -> dt.date:
    return dt.date.today()


def _date(v: Any) -> dt.date | None:
    if isinstance(v, dt.date):
        return v
    s = str(v or "")[:10]
    try:
        return dt.date.fromisoformat(s)
    except ValueError:
        return None


# ─────────────────────────────────────────────────────────────────────────────
# 게이트 — 어긋나면 즉시 「불가」. 전부 계산이다
# ─────────────────────────────────────────────────────────────────────────────
# 지자체·지역기관 표지. 이 기관이 내는 공고의 지역코드는 「신청 제한」이다.
# 중앙부처가 내는 공고의 지역코드는 「수행 지역」일 수 있어 뜻이 다르다.
#
# ⚠ 실측 버그였다. 처음엔 지자체를 `(도|시|군|구)$` 로만 봤는데, 실제 데이터에는
#   「관악구청」·「광명시청」·「대전광역시 서구청」이 들어 있다. 이건 `(부|처|청)$` 에
#   먼저 걸려 **중앙부처로 분류되고 지역 게이트가 풀렸다** — 구청 공고가 「확인필요」로
#   올라왔다. 「청」으로 끝나는 것 중 지자체를 먼저 가려야 한다.
_지역기관 = re.compile(
    r"((시|군|구)청$"                                  # 관악구청 · 광명시청 · 서구청
    r"|(특별시|광역시|특별자치시|특별자치도)"           # 서울특별시 · 대전광역시
    r"|(도|시|군|구)$"                                  # 경상북도 · 서울시
    r"|지역본부|지역센터"                               # LH 경기남부지역본부
    r"|테크노파크|진흥원|창조경제혁신센터|경제진흥원|산업진흥원"
    r"|디지털혁신|재단|공단|센터$|산학협력)")
# ⚠ 실측(id 399): 「한국생산성본부」가 "부/처/청으로 끝나면 중앙부처"에 걸렸다 —
#   "본부"(headquarters)도 "부"로 끝난다. "본부"로 끝나는 이름을 먼저 뺀다 —
#   중소벤처기업부·산업통상자원부처럼 진짜 중앙부처는 "본부"로 안 끝난다.
_중앙부처 = re.compile(r"(?<!본)(부|처|청)$")

# 지역 표기가 출처마다 다르다. 기업마당은 「전남광주」로 묶어 쓰고, 공고문에서 넣은
# 행은 「광주」다. 문자열이 같아야 통과시키면 광주 공고를 우리 지역이 아니라고 버린다.
# → 한쪽이 다른 쪽을 품고 있으면 같은 지역으로 본다(전남광주 ⊃ 광주 · 전남).
def 지역겹침(공고지역: set[str], 우리지역: set[str]) -> set[str]:
    """겹치는 지역 표기를 돌려준다. 비어 있으면 겹치지 않는다."""
    맞음: set[str] = set()
    for a in 공고지역:
        for b in 우리지역:
            if a == b or (len(a) >= 2 and len(b) >= 2 and (a in b or b in a)):
                맞음.add(a)
    return 맞음


# 지역코드(약칭) → 본문·요약에 실제로 쓰이는 표기들. "도" 붙는 것과 안 붙는 것이 섞여 있다.
_지역_전체명 = {
    "강원": ("강원도", "강원"), "경기": ("경기도", "경기"),
    "경북": ("경상북도", "경북"), "경남": ("경상남도", "경남"),
    "충북": ("충청북도", "충북"), "충남": ("충청남도", "충남"),
    "전북": ("전라북도", "전북"), "전남광주": ("전라남도", "광주", "전남"),
    "제주": ("제주특별자치도", "제주"),
}


def _지역명시됨(text: str, 지역코드들: set[str]) -> tuple[bool, str]:
    """요약·본문에 「OO도 內 …」류로 지역이 직접 명시돼 있는지. 있으면 (True, 매치문구)."""
    flat = F.strip_ws(text or "")
    for 코드 in 지역코드들:
        for 표기 in _지역_전체명.get(코드, (코드,)):
            m = re.search(rf"{re.escape(표기)}(?:도)?(내|소재|관내|지역)", flat)
            if m:
                return True, m.group(0)
    return False, ""


def 지역제한_성격(ann: dict) -> tuple[bool, str]:
    """지역코드를 신청 제한으로 볼 것인가. (제한이다, 사유).

    ⚠ 섀도 대조에서 나온 문제다. LLM 이 유일하게 「가능」이라 한 공고 41 은
      소관부처가 경상북도·전문기관이 포항테크노파크였고, 요약에 「지역 제조기업의
      자율제조 전환을 지원」이라고 적혀 있었다 — 규칙 엔진이 맞았다.
      반대로 소관부처가 중앙부처인 공고(384건 중 10건)는 지역코드가 수행지역일 수
      있다. 그건 「불가」로 확정하지 않고 사람에게 묻는다 —
      「불가」로 잘못 찍힌 공고는 다시 볼 기회가 없다(§6 설계 원칙 4번).

    ⚠ 실측(id 399, 2026-09-04): 「한국생산성본부」가 아래 _중앙부처(…끝나면 중앙부처로
      본다) 정규식에 걸렸다 — "본부"도 "부"로 끝나기 때문이다. 실제론 정부부처가
      아니라 그냥 운영기관 이름이라 오판이었다. 그런데 요약에 "강원도 內 창업・
      벤처기업"이라고 **직접 적혀 있었다.** 기관 이름을 접미사로 추측하는 것보다
      본문에 지역이 명시됐는지를 먼저 보는 게 훨씬 안전하다 — 그래서 이 검사를
      기관 이름 추측보다 **앞에** 둔다.
    """
    공고지역 = set(ann.get("지역코드") or [])
    명시됨, 매치 = _지역명시됨(ann.get("요약"), 공고지역)
    if not 명시됨:
        명시됨, 매치 = _지역명시됨(ann.get("본문"), 공고지역)
    if 명시됨:
        return True, f"요약·본문에 지역이 직접 명시됨 (「{매치}」)"

    # 기업마당은 지자체 공고 사업명 앞에 [지역] 태그를 붙인다(실측 429건 중 243건).
    # 태그가 공고 지역코드와 맞으면 그것만으로 지자체 공고임이 확정된다.
    사업명 = (ann.get("사업명") or "").strip()
    m = re.match(r"\[([^\]]{1,12})\]", 사업명)
    if m:
        태그 = m.group(1).strip()
        for 지역 in (ann.get("지역코드") or []):
            if 태그 == 지역 or 태그 in 지역 or 지역 in 태그:
                return True, f"사업명에 [{태그}] 태그가 붙은 지자체 공고다"

    for 칸 in ("소관부처", "전문기관"):
        기관 = (ann.get(칸) or "").strip()
        if 기관 and _지역기관.search(기관):
            return True, f"{칸} 「{기관}」이 지역기관이다"
    for 칸 in ("소관부처", "전문기관"):
        기관 = (ann.get(칸) or "").strip()
        if 기관 and _중앙부처.search(기관):
            return False, f"{칸} 「{기관}」이 중앙부처다 — 지역코드가 수행지역일 수 있다"
    # 기관을 모르면 제한으로 본다. 기업마당 공고는 사업명에 [지역] 태그가 붙는 것이 대부분이다.
    return True, "발주 기관을 알 수 없어 지역코드를 신청 제한으로 본다"


def _gates(ann: dict, company: dict, feats: list[F.Feature]) -> list[dict]:
    """게이트 결과 목록. {키, 통과, 사유, 근거, 신뢰도, 보류?}.

    통과=False 이고 보류가 아닌 게이트가 하나라도 있으면 「불가」다.
    **보류=True** 는 「어긋나 보이지만 확정하지 않는다」 — 확인필요로 넘긴다.

    ⚠ 판단할 근거가 없는 게이트는 **목록에 넣지 않는다.** 「모르니까 통과」도
      「모르니까 탈락」도 둘 다 거짓이다. 모르는 것은 확인필요로 간다.
    """
    by키: dict[str, F.Feature] = {}
    for f in feats:
        if f.특징키 not in by키 or f.규칙신뢰도 > by키[f.특징키].규칙신뢰도:
            by키[f.특징키] = f

    out: list[dict] = []

    def put(키: str, 통과: bool, 사유: str, 근거: str, 신뢰도: float,
            보류: bool = False) -> None:
        g = {"키": 키, "통과": 통과, "사유": 사유, "근거": 근거, "신뢰도": round(신뢰도, 3)}
        if 보류:
            g["보류"] = True
        out.append(g)

    # ① 접수마감 — 날짜 비교다. 마감유형이 상시·수시면 마감이 없다
    종료 = _date(ann.get("접수종료"))
    if 종료 and (ann.get("마감유형") or "dated") == "dated":
        남음 = (종료 - _today()).days
        put("접수마감", 남음 >= 0,
            f"접수종료 {종료} — {'D' + f'{남음:+d}' if 남음 < 0 else f'D-{남음}'}",
            f"공고 접수종료 {종료}, 오늘 {_today()}", 1.0)

    # ② 지역제한 — 배열 교집합이다. 「전국」은 언제나 통과
    공고지역 = set(ann.get("지역코드") or ([ann["지역"]] if ann.get("지역") else []))
    우리지역 = set(company.get("지역코드") or [])
    if 공고지역:
        통과 = ("전국" in 공고지역) or bool(지역겹침(공고지역, 우리지역))
        제한이다, 성격 = 지역제한_성격(ann)
