    ok = 0
    for (aid, 특징키, 텍스트, 판정, 사유, 답변자), vec in zip(SEED, vecs):
        rest.insert("judgment_semantic", {
            "announcement_id": aid,
            "텍스트": 텍스트,
            "임베딩": vec,
            "임베딩모델": S.MODEL_NAME,
            "판정": 판정,
            "특징키": 특징키,
            "사유": 사유,
            "답변자": 답변자,
        })
        ok += 1
        print(f"  [{aid}] {특징키} · {판정} · {답변자}")

    print(f"\n완료 {ok}/{len(SEED)}건 저장")


