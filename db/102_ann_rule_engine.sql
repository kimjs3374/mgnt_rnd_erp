-- -----------------------------------------------------------------------------
-- 6. 섀도 대조 뷰 — 규칙 판정을 LLM 판정 옆에 놓는다
--
--    「LLM 없이도 된다」는 주장은 이 뷰에서만 나온다. 지어낸 수치를 쓰지 않는다.
--    LLM 이 이미 판정한 건에만 행이 생긴다(현재 37건).
-- -----------------------------------------------------------------------------
create or replace view app.v_ann_rule_vs_llm as
select
  r.announcement_id,
  a.사업명,
  a.출처,
  r.엔진버전,
  r.판정                                  as 규칙_판정,
  r.점수                                  as 규칙_점수,
  r.확신도                                as 규칙_확신도,
  r.커버리지,
  e.확정_판정                             as llm_판정,
  (e.ai_제안 ->> '점수')::int             as llm_점수,
  e.ai_확신도                             as llm_확신도,
  (r.판정 = e.확정_판정)                  as 판정일치,
  abs(r.점수 - coalesce((e.ai_제안 ->> '점수')::int, r.점수)) as 점수차,
  e.정정여부                              as 사람정정,
  r.llm_호출
from app.ann_rule_scores r
join app.announcements a          on a.id = r.announcement_id
join app.eligibility_decisions e  on e.announcement_id = r.announcement_id;

comment on view app.v_ann_rule_vs_llm is
  '규칙 판정 vs LLM 판정 섀도 대조. 일치율·점수차의 유일한 근거. '
  'LLM 이 판정한 건에만 행이 생긴다 — 규칙 엔진의 커버리지가 더 넓어서 대부분의 공고는 여기 없다.';

-- -----------------------------------------------------------------------------
-- 7. 커버리지 지표 뷰 — 「836건 중 규칙만으로 몇 건, LLM 호출 몇 회」
-- -----------------------------------------------------------------------------
create or replace view app.v_ann_rule_coverage as
select
  r.엔진버전,
  count(*)                                                  as 판정건수,
  count(*) filter (where r.llm_호출 = 0)                     as llm없이_판정,
  sum(r.llm_호출)                                            as llm_호출_합,
  count(*) filter (where r.판정 = '가능')                    as 가능,
  count(*) filter (where r.판정 = '불가')                    as 불가,
  count(*) filter (where r.판정 = '확인필요')                as 확인필요,
  count(*) filter (where r.판정 = '요건미확인')              as 요건미확인,
  (select count(*) from app.announcements)                   as 전체공고,
  round(avg(r.커버리지), 3)                                  as 평균커버리지
from app.ann_rule_scores r
group by r.엔진버전;

comment on view app.v_ann_rule_coverage is
  '규칙 엔진 커버리지 지표. 화면·챗봇이 「전체 N건 중 LLM 호출 0회로 M건 판정」을 여기서 읽는다. '
  '요건미확인은 실패가 아니라 정직한 상태다 — 본문을 확보하면 판정된다.';

