-- =============================================================================
-- 106_event_notice.sql — 규칙 판정에 "해당없음"(행사·교육 공지) 값을 추가한다
--
--   왜: K-Startup 첨부없는 공고 376건 중 상당수가 무료 교육·멘토링·네트워킹
--   "행사"다(실측: "[창업 교육] 투자자가 보는 기업 가치와 IR 전략" — 신청대상
--   "해당 주제에 관심이 있는 누구나(제한 없음)", 교육비 무료, 일시·장소만 있고
--   지원금·지원조건이 없다). 사용자 지적(2026-09-04): "이벤트 공지는 별도
--   필터링으로 제외시켜야함".
--
--   지원분야 태그(멘토링ㆍ컨설팅ㆍ교육 등)만으로는 못 가른다 — 실측으로 확인했다.
--   같은 태그 안에 진짜 지원사업(전시회 참가비 지원 등)이 섞여 있다. 그래서
--   "불가"(자격이 안 됨)나 "요건미확인"(못 읽음)으로 눙치지 않는다 — 둘 다 틀린
--   말이다. 이건 자격 문제가 아니라 애초에 "지원금 신청"이 아닌 공지다.
--   새 값 "해당없음"을 추가해 그 사실을 있는 그대로 남긴다.
--
--   설계 원칙: 추가만 한다. 기존 CHECK 제약을 넓히는 것 — DROP·ALTER TYPE 없음.
--   적용:     cd /web/rnd && ./db/psql.sh -f db/106_event_notice.sql
--   되돌리기: 파일 맨 아래
-- =============================================================================

begin;

alter table app.ann_rule_scores drop constraint if exists chk_rule_판정;
alter table app.ann_rule_scores add constraint chk_rule_판정
  check (판정 in ('가능', '불가', '확인필요', '요건미확인', '해당없음'));

comment on column app.ann_rule_scores.판정 is
  '가능 | 불가 | 확인필요 | 요건미확인(본문을 못 읽었다) | 해당없음(지원금 신청이 아닌 '
  '행사·교육 공지 — 자격 문제가 아니라 애초에 판정 대상이 아니다).';

commit;

notify pgrst, 'reload schema';

