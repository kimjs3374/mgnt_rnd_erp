-- =============================================================================
-- 109_evidence_travel_meeting.sql — 출장·회의 증빙 요건을 실무 서류명으로 맞춘다
--
--   무엇을 바꾸나 (2026-09-04 사용자 지시, 두 메시지)
--     ① "활동비에서 출장비 증빙파일은 여비 지출결의서, 차량운행거리, 출장보고서,
--        출장 증빙 서류가 있으니"
--     ② "활동비의 회의비(필수서류)에서는 사전품의서, 회의록, 지출결의서, 매출전표(영수증)도 넣어줘"
--
--   **지우지 않고 더한다.** 사용자가 "빼라"고 하지 않았고, 기존 출장신청서·회의참석자명단이
--   실제로 안 쓰인다는 근거도 없다. 겹치는 서류는 사용자가 준 말투로 이름만 맞춘다
--   (출장결과보고서→출장보고서, "출장 증빙 서류(교통·숙박 영수)"→"출장 증빙 서류").
--
--   순번을 어떻게 배정했나
--     기존 출장(11~13)·회의(14~15) 순번을 유지하고, 새 항목은 그 사이·뒤에 소수 자리로 끼워 넣지
--     않고 **뒤에 이어 붙인다**(16~21) — 순번은 정렬에만 쓰이고 화면에 안 보인다
--     (`components/evidence-attachments.tsx` 옛 주석: "순번은 화면에는 안 낸다").
--     매그나텍 실제 폴더 번호가 아닌 항목(이번 추가분)은 원문에 그렇게 적어 둔다.
--
--   차량운행거리는 왜 「해당시」인가
--     자가용을 써서 이동한 경우에만 발생하는 서류다(항공·철도·대중교통 이용 시에는 없다).
--     나머지 셋(여비 지출결의서·출장보고서·출장 증빙 서류, 회의 넷 전부)은 매 건 발생하는
--     서류라 필수로 둔다. 틀렸으면 화면에서 바로 고칠 수 있다(필수여부는 DB 값 하나다).
--
--   적용: cd /web/rnd && ./db/psql.sh -f db/109_evidence_travel_meeting.sql
--   되돌리기: 파일 맨 아래
-- =============================================================================

begin;

-- ── 기존 항목 이름을 사용자가 준 말투로 맞춘다 ────────────────────────────────
update app.evidence_requirements
   set 서류명 = '출장보고서'
 where 비목_대분류 = 'ACTIVITY' and 구분 = '출장' and 서류명 = '출장결과보고서';

update app.evidence_requirements
   set 서류명 = '출장 증빙 서류'
 where 비목_대분류 = 'ACTIVITY' and 구분 = '출장' and 서류명 = '출장 증빙 서류(교통·숙박 영수)';

-- ── 출장 — 새로 더하는 둘 ──────────────────────────────────────────────────
insert into app.evidence_requirements
  (비목_대분류, 구분, 순번, 서류명, 필수여부, 개인정보포함, 원문, 출처)
values
  ('ACTIVITY','출장',16,'여비 지출결의서', true, false, null,
   '2026-09-04 사용자 지시 — 활동비 출장비 증빙파일 목록'),
  ('ACTIVITY','출장',17,'차량운행거리',   false,false,
   '자가용으로 이동한 경우에만 발생한다. 항공·철도·대중교통 이용 시에는 해당 없음.',
   '2026-09-04 사용자 지시 — 활동비 출장비 증빙파일 목록')
on conflict do nothing;

-- ── 회의 — 새로 더하는 셋(회의록은 이미 있어 겹치지 않는다) ────────────────
insert into app.evidence_requirements
  (비목_대분류, 구분, 순번, 서류명, 필수여부, 개인정보포함, 원문, 출처)
values
  ('ACTIVITY','회의',18,'사전품의서',       true, false, null,
   '2026-09-04 사용자 지시 — 활동비 회의비 필수서류 목록'),
  ('ACTIVITY','회의',19,'지출결의서',       true, false, null,
   '2026-09-04 사용자 지시 — 활동비 회의비 필수서류 목록'),
  ('ACTIVITY','회의',20,'매출전표(영수증)', true, false, null,
   '2026-09-04 사용자 지시 — 활동비 회의비 필수서류 목록')
on conflict do nothing;

commit;

notify pgrst, 'reload schema';

