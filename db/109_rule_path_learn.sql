-- 109_rule_path_learn.sql — 판정경로에 「학습」을 받는다
--
--   사용자 지적(2026-09-04): "계속 이런식이면 학습해서 걸러낸다는 로직이 동작을
--   안한다고 봐야되는게 맞지않냐?" — 맞았다. judgment_semantic 은 쌓이고 검색도
--   되는데 판정을 내리는 경로가 그걸 한 번도 안 읽고 있었다(호출부가 챗봇 도구와
--   화면 버튼 둘뿐). 그래서 규칙엔진 r9 에 「학습」 분기를 넣었다 — 같은 특징키로
--   과거 사람 판정이 2건 이상 모두 같은 결론이면 그 결론을 쓴다.
--
--   그 판정을 저장하려니 chk_rule_경로 가 '규칙'·'규칙+사람'·'LLM폴백' 만 받아
--   20건이 통째로 저장에 실패했다(23514). 경로를 넓힌다 —
--   **어떤 경로로 나온 판정인지는 지우면 안 되는 정보다.** 규칙이 계산으로 확정한
--   것과 과거 판정을 근거로 미룬 것은 신뢰도가 다르고, 화면에서 "왜 불가인지"를
--   되짚어 정정하려면 경로가 남아 있어야 한다.
--
--   추가하는 값
--     규칙+학습        규칙이 확정 못 한 자리에서 과거 사람 판정을 따랐다
--     규칙+학습+사람   위에 더해 사람 답변(ann_feature_answers)까지 얹혔다
--
--   설계 원칙: 추가만 한다. 기존 값 3종은 그대로 둔다(과거 행을 손대지 않는다).
--   적용:     cd /web/rnd && ./db/psql.sh -f db/109_rule_path_learn.sql
--   되돌리기: 파일 맨 아래
-- =============================================================================

begin;

alter table app.ann_rule_scores drop constraint if exists chk_rule_경로;

alter table app.ann_rule_scores add constraint chk_rule_경로
  check (판정경로 = any (array[
    '규칙',            -- 계산으로 확정. 가장 세다
    '규칙+사람',       -- 사람이 답한 회사 정보를 얹었다
    '규칙+학습',       -- 과거 사람 판정(judgment_semantic)을 근거로 따랐다
    '규칙+학습+사람',  -- 둘 다
    'LLM폴백'          -- 규칙으로 안 되어 LLM 이 판정했다
  ]));

comment on column app.ann_rule_scores.판정경로 is
  '이 판정이 어디서 나왔는지. 규칙(계산 확정) · 규칙+사람(사람 답변 반영) · '
  '규칙+학습(과거 사람 판정을 따름, 2026-09-04 추가) · 규칙+학습+사람 · LLM폴백. '
  '「규칙+학습」은 확신도가 유사도 그대로라 대개 0.70 아래다 — 자동 확정이 아니라 '
  '사람이 정정할 수 있는 상태로 남는다.';

commit;

notify pgrst, 'reload schema';

