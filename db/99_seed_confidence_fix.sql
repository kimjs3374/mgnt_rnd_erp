-- 99_seed_confidence_fix.sql — 시드에 있던 **코드로는 나올 수 없는 상태** 하나를 고친다
--
--   무엇이 잘못돼 있었나
--     `expenses` id=5 (컴퓨존 · 노트북 1대 · 2024-06-11) 가
--     **ai_확신도 0.580 · 상태 확정 · 정정여부 false** 였다. 이 조합은 화면으로 못 만든다 —
--     `app/actions/expenses.ts` 의 `confirmExpense` 가 0.70 미만이면 [이대로 확정]을 거부하고
--     (`CONFIDENCE_THRESHOLD = 0.7`), 정정 경로는 사유가 필수라 `정정여부 = true` 가 된다.
--     시드를 DB 에 직접 넣으면서 그 게이트를 지나치지 않은 것이다.
--
--     **심사장에서 「58%인데 왜 확정됐죠?」 한 마디에 답이 없다.** 확신도 게이트가 이 제품의
--     핵심 주장(§6-3 「프롬프트를 믿지 않는다, 코드로 막는다」)인데 그 반례가 표에 떠 있는 셈이다.
--
--   왜 확신도만 올렸나 — 다른 길은 전부 데모 자산을 깎는다
--     · 상태를 「검토대기」로 → **판단 우선순위 2층(과거 집행)이 빈다.** id=5 는 5:00 장면에서
--       「우리 회사는 노트북을 ACTIVITY 로 처리해왔다」의 근거다. 검토대기로 돌리면 그 근거가 사라지고
--       검토대기도 1건 → 2건이 되어 대본 숫자가 어긋난다.
--     · 정정 이력을 붙여 확정 근거를 만든다 → **CLAUDE.md §9 절대 규칙 위반.**
--       「노트북 정정 이력은 0건 — 절대 심지 않는다. 5:00 에서 **현장에서 처음** 발생해야 한다.」
--       미리 심으면 재투입 때 확신도가 이미 올라가 있어 발표 전체의 논지가 성립하지 않는다.
--     · 확신도를 지운다(null) → 근거 문구까지 지워야 앞뒤가 맞고, 그러면 `decisions` 한 줄도
--       뜻을 잃는다. §9 는 decisions 를 **더 심으라**고 하지 줄이라고 하지 않는다.
--
--     남는 것은 **확신도를 게이트 위로 올리는 것**뿐이다. 0.580 → 0.720.
--     지어낸 값을 지어낸 값으로 바꾸는 것이지(시드 전체가 합성 데이터다) 사실을 왜곡하는 게 아니다.
--     0.72 로 둔 이유: 「사무용 기기로 판단」이라는 근거 문구가 말하는 **애매함**은 남기고
--     통과선만 겨우 넘게 한다. 90% 대로 올리면 그 뉘앙스가 사라진다.
--
--   `decisions.ai_제안` 스냅샷도 같이 고친다 — 그게 「그때 AI 가 뭐라고 했는지」의 박제라,
--   본표와 다르면 어느 쪽이 사실인지 알 수 없게 된다.
--
--   멱등하다. 두 번 돌려도 0.580 인 것만 바꾸므로 아무 일도 일어나지 않는다.
--   적용: cd /web/rnd && ./db/psql.sh -f db/99_seed_confidence_fix.sql
--   되돌리기: 파일 맨 아래
-- =============================================================================

begin;

update app.expenses
   set ai_확신도 = 0.720
 where id = 5
   and ai_확신도 = 0.580;

update app.decisions
   set ai_제안 = jsonb_set(ai_제안, '{확신도}', to_jsonb(0.720::numeric))
 where expense_id = 5
   and (ai_제안->>'확신도')::numeric = 0.580;

commit;

-- 확인 — 「확정인데 확신도가 게이트 아래이고 정정도 아닌」 건이 남아 있으면 안 된다. 0 이어야 한다.
select count(*) as 남은_모순건
  from app.expenses e
  left join app.decisions d on d.expense_id = e.id
 where e.상태 = '확정'
   and e.ai_확신도 is not null
   and e.ai_확신도 < 0.70
   and coalesce(d.정정여부, false) = false;

