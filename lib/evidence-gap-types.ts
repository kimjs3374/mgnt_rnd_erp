/**
 * 증빙 구멍의 행 타입. **서버와 클라이언트가 같이 읽는다.**
 *
 * `lib/queries-evidence-gap.ts` 는 `server-only` 라 클라이언트 컴포넌트가 거기서 타입을
 * 가져오면 빌드가 깨진다. 그래서 타입만 여기 둔다(`lib/evidence-types.ts` 와 같은 이유).
 */

/** 사람이 사유를 달아 「없어도 된다」고 정리한 칸(db/114). 미비에서 빠지지만 기록엔 남는다. */
export type 면제칸 = {
  요건_id: number
  서류명: string
  사유: string
  행위자: string
  일시: string
}

/** 목록에 그대로 찍는 한 줄 — 「어느 집행의 무엇이 비었나」. */
export type 빈건 = {
  집행_id: number
  일자: string | null
  거래처: string | null
  합계: number | null
  비목_대분류: string | null
  /** 빠진 **필수** 서류 이름들. 이름이 있어야 사람이 무엇을 준비할지 안다. */
  빠진서류: string[]
  /** 그 서류들의 요건 id — 면제 버튼이 서버에 보낼 값. 이름만으론 어느 칸인지 모른다. */
  빠진요건ids: number[]
  /** 이 건에서 사유를 달고 면제한 칸들. 「왜 정상인가」가 여기 있다. */
  면제: 면제칸[]
}

export type 증빙구멍 = {
  /** 증빙이 필요한 집행 건수(그 과제에서). */
  집행건: number
  /** 그중 필수 서류가 하나라도 빈 건수. */
  빈집행건: number
  /** 안 채운 필수 서류 칸 수(건 × 서류). 「얼마나 남았나」는 이 숫자가 말해 준다. */
  빈칸: number
  /** 사유를 달아 면제한 칸 수. 미비에는 안 들어가지만 **몇 칸을 면제했는지는 보여준다.** */
  면제칸: number
  /**
   * 서류가 빈 집행 건 id — **일자가 이른 것부터.**
   * 「어디가 비었는지」로 바로 보내려면 과제가 아니라 **그 집행 건**을 열어야 한다.
   */
  빈집행ids: number[]
  /** 빈 건들의 상세 — 일자가 이른 것부터. 목록·바로가기가 이걸 쓴다. */
  상세: 빈건[]
}
