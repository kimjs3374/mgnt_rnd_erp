export const won = (n: number | null | undefined) =>
  n == null ? "—" : "₩" + n.toLocaleString("ko-KR")

export const dday = (d: string | null) => {
  if (!d) return null
  const diff = Math.ceil(
    (new Date(d + "T00:00:00").getTime() - new Date().setHours(0, 0, 0, 0)) / 86_400_000,
  )
  return diff
}
