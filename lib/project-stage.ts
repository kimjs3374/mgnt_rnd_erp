/**
 * 과제가 지금 어느 단계인가 — **신청중 → 수행중 → 사업종료**.
 *
 * 사용자 지시(2026-09-03): 과제사업을 이 셋으로 나눠 관리하고,
 * **선정되면 수행중으로, 수행기간이 끝나면 사업종료로 저절로 넘어가게** 한다.
 *
 * ★ 그래서 단계는 **저장하지 않고 계산한다.**
 *   저장된 `상태` 를 그대로 믿으면 「수행기간이 끝나면 넘어간다」가 성립하지 않는다 —
 *   아무도 손대지 않는 한 그 값은 영원히 `수행중` 이다. 날짜는 저절로 지나가지만
 *   저장값은 저절로 안 바뀐다. 연차를 기간에서 계산한 것과 같은 이유다(`lib/fiscal-year.ts`).
 *
 * ⚠ 그래도 저장된 `상태` 를 버리지 않는다. **일찍 끝난 과제(중단·조기종료)** 는 종료일이
 *   남아 있어도 끝난 것이고, 그건 날짜로 알 수 없다. 그래서 판정은 **둘 중 하나라도 끝났으면 끝**이다.
 *   반대로 저장값이 `수행중` 인데 종료일이 지났으면 화면이 사업종료로 옮기고,
 *   **저장값을 맞출지는 사람이 누른다**(`app/actions/project-stage.ts`).
 *   조회하는 화면이 조용히 DB 를 고치면 누가 언제 바꿨는지가 사라진다(CLAUDE.md §6-1).
 */
export type 과제단계 = "신청중" | "수행중" | "사업종료"

/** 메뉴·제목에 쓰는 이름과 경로. 여기 하나만 고치면 사이드바·화면·브레드크럼이 같이 따라온다. */
export const 단계정의: { 단계: 과제단계; 경로: string; 설명: string }[] = [
  {
    단계: "신청중",
    경로: "/projects/applying",
    설명: "지원을 넣고 결과를 기다리는 건. 선정을 기록하면 수행중으로 넘어간다.",
  },
  {
    단계: "수행중",
    경로: "/projects",
    설명: "선정되어 협약기간 안에 있는 과제. 여기서 계상하고 집행하고 정산한다.",
  },
  {
    단계: "사업종료",
    경로: "/projects/closed",
    설명: "수행기간이 끝난 과제. 정산·결과보고가 남아 있을 수 있다.",
  },
]

export const 단계경로 = (s: 과제단계) => 단계정의.find((d) => d.단계 === s)?.경로 ?? "/projects"

type 판정입력 = {
  상태: string
  선정결과?: string | null
  종료일?: string | null
}

/**
 * 미선정된 건인가. 세 단계 **어디에도 넣지 않는다** — 과제가 되지 못한 건이다.
 * 그 건은 지원사업 대장(`/programs`)에서 「왜 떨어졌나」와 함께 본다.
 */
export function 미선정인가(r: 판정입력): boolean {
  return (r.선정결과 ?? "") === "미선정"
}

export function 단계판정(r: 판정입력, 기준일?: string): 과제단계 {
  // ① 아직 결과를 기다리는 건이 먼저다. 신청 건은 사업기간이 「예정」으로 들어가 있어서
  //    종료일부터 보면 시작도 안 한 과제가 사업종료로 떨어진다.
  if (r.상태 === "신청중") return "신청중"
  const 결과 = r.선정결과 ?? ""
  if (결과 === "접수" || 결과 === "발표심사") return "신청중"

  // ② 끝났는가 — **저장값과 날짜 중 하나라도** 끝이라고 하면 끝이다.
  //    저장값만 보면 기간이 지나도 안 넘어가고(사용자가 원한 자동 전환이 깨진다),
  //    날짜만 보면 조기 종료·중단된 과제를 계속 수행중으로 세게 된다.
  if (r.상태 === "종료") return "사업종료"
  const 끝 = String(r.종료일 ?? "").slice(0, 10)
  if (/^\d{4}-\d{2}-\d{2}$/.test(끝) && 끝 < (기준일 ?? 오늘())) return "사업종료"

  return "수행중"
}

/**
 * 화면은 사업종료로 옮겼는데 **저장된 `상태` 는 아직 수행중**인가.
 *
 * 이 상태를 그냥 두면 목록은 「사업종료」인데 배지는 「수행중」이라 서로 다른 말을 한다.
 * 게다가 `bot/mcp_server.py` 는 저장값을 읽어 답하므로 봇만 옛말을 하게 된다.
 * 그래서 화면이 짚어 주고, 맞출지는 사람이 누른다.
 */
export function 종료표시가_밀렸나(r: 판정입력, 기준일?: string): boolean {
  return 단계판정(r, 기준일) === "사업종료" && r.상태 !== "종료"
}
