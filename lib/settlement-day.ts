/**
 * 매월 정산일과 D-day — 순수 함수. (2026-09-04 사용자 지시)
 *
 * 규칙: **매달 25일.** 그 날이 주말·공휴일이면 **앞으로 당긴다**(직전 영업일).
 *   · 25일이 토요일 → 금요일 24일
 *   · 25일이 일요일 → 금요일 23일
 *   · 25일이 평일 공휴일 → 그 직전 영업일(대부분 하루 앞, 연휴면 더 앞)
 *
 * 사용자는 「주말·공휴일이면 금요일」이라고 했다. **주말은 당기면 정확히 금요일이 된다.**
 * 평일 공휴일까지 굳이 그 주 금요일로 보내면 마감이 며칠씩 앞당겨져 오히려 이상해서,
 * 「직전 영업일」로 뒀다. 무조건 금요일이어야 하면 `직전영업일()` 한 줄만 바꾸면 된다.
 *
 * 날짜는 `YYYY-MM-DD` **문자열 그대로** 다룬다 — `new Date()` 로 바꾸면 시간대 때문에
 * 하루가 밀린다(`lib/fiscal-year.ts` · `lib/participation.ts` 와 같은 이유).
 */

