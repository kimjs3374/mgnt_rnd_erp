const 공휴일집합 = new Set<string>(공휴일_2026)

const iso = (y: number, m: number, d: number) =>
  `${y}-${String(m).padStart(2, "0")}-${String(d).padStart(2, "0")}`

/** 요일. 0=일 … 6=토. UTC 로만 만들어 시간대에 안 흔들리게 한다. */
export function 요일(날: string): number {
  const [y, m, d] = 날.split("-").map(Number)
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay()
}

export const 주말인가 = (날: string) => 요일(날) === 0 || 요일(날) === 6
export const 공휴일인가 = (날: string) => 공휴일집합.has(날)
export const 쉬는날인가 = (날: string) => 주말인가(날) || 공휴일인가(날)

function 하루전(날: string): string {
  const [y, m, d] = 날.split("-").map(Number)
  const t = new Date(Date.UTC(y, m - 1, d))
  t.setUTCDate(t.getUTCDate() - 1)
  return iso(t.getUTCFullYear(), t.getUTCMonth() + 1, t.getUTCDate())
}

/** 쉬는 날이면 앞으로 당긴다. 연휴면 연휴를 다 지나 앞 영업일까지 간다. */
export function 직전영업일(날: string): string {
  let cur = 날
  // 열흘이면 어떤 연휴도 넘는다. 무한 루프를 코드로 막는다.
  for (let i = 0; i < 10 && 쉬는날인가(cur); i++) cur = 하루전(cur)
  return cur
}

export const 오늘 = () => new Date().toISOString().slice(0, 10)

const 요일이름 = ["일", "월", "화", "수", "목", "금", "토"]

export type 정산일 = {
  /** 실제 마감일(당겨진 뒤). */
  날: string
  /** 원래 기준일(그 달 25일). 당겨졌는지 보여주려고 같이 준다. */
  원래: string
  /** 당겨졌는가 — 그 이유를 화면이 말한다. */
  당겨짐: boolean
  이유: "주말" | "공휴일" | null
  요일: string
  /** 오늘로부터 며칠 남았나. 0 이면 오늘이다. */
  남은일: number
  /** 음력 공휴일이 판단에 끼어들었나 — 그러면 확인이 필요하다. */
  확인필요: boolean
}

function 일수차(a: string, b: string): number {
  const p = (s: string) => {
    const [y, m, d] = s.split("-").map(Number)
    return Date.UTC(y, m - 1, d)
  }
  return Math.round((p(b) - p(a)) / 86400000)
}

/** 그 달의 정산일. 기준일 25일을 쉬는 날이면 앞으로 당긴다. */
export function 그달정산일(y: number, m: number): { 날: string; 원래: string } {
  const 원래 = iso(y, m, 25)
  return { 날: 직전영업일(원래), 원래 }
}

/**
 * **다음 정산일.** 이번 달 정산일이 아직 안 지났으면 그것, 지났으면 다음 달.
 * 오늘이 정산일이면 오늘(D-0)이다 — 「오늘이 마감」이 제일 중요한 말이다.
 */
export function 다음정산일(기준일?: string): 정산일 {
  const 오 = 기준일 ?? 오늘()
  const [y, m] = 오.split("-").map(Number)

  let { 날, 원래 } = 그달정산일(y, m)
  if (일수차(오, 날) < 0) {
    const ny = m === 12 ? y + 1 : y
    const nm = m === 12 ? 1 : m + 1
    ;({ 날, 원래 } = 그달정산일(ny, nm))
  }

  const 당겨짐 = 날 !== 원래
  const 이유 = !당겨짐 ? null : 공휴일인가(원래) ? "공휴일" : "주말"
  // 당기는 동안 지난 날들 중 음력 공휴일이 있었으면 확인이 필요하다.
  let 확인필요 = false
  for (let cur = 원래; 일수차(날, cur) >= 0; cur = 하루전(cur)) {
    if (확인필요_공휴일.has(cur)) 확인필요 = true
    if (cur === 날) break
  }

  return {
    날,
    원래,
    당겨짐,
    이유,
    요일: 요일이름[요일(날)],
    남은일: 일수차(오, 날),
    확인필요,
  }
}
