// 참여기간·참여율 규칙 검산. **브라우저가 필요 없다** — 순수 함수라 값으로 바로 확인한다.
//
// `lib/participation.ts` 는 TS 라 그대로 import 할 수 없어서, 같은 식을 여기 옮겨 적지 않고
// **tsc 가 뱉은 JS** 를 부른다(`npx tsc lib/participation.ts --outDir /tmp/pcheck ...`).
// 식을 두 벌 적으면 한쪽만 고쳐지고, 그 어긋남은 검산의 뜻을 없앤다.
const mod = await import(process.argv[2] ?? "/tmp/pcheck/participation.js")
const { 참여종료일계산, 국책참여율_초과, 국책인가, 기간겹침 } = mod

let 실패 = 0
const eq = (실제, 기대, 말) => {
  const ok = JSON.stringify(실제) === JSON.stringify(기대)
  if (!ok) 실패++
  console.log(`   ${ok ? "✓" : "✗"} ${말}${ok ? "" : `  (얻은 값: ${JSON.stringify(실제)})`}`)
}

console.log("① 참여종료일 = 시작일 + 개월수 − 1일")
eq(참여종료일계산("2026-01-01", 6), "2026-06-30", "2026-01-01 + 6개월 = 2026-06-30")
eq(참여종료일계산("2022-06-01", 24), "2024-05-31", "2022-06-01 + 24개월 = 2024-05-31 (과제 13 협약기간과 같다)")
eq(참여종료일계산("2026-01-31", 1), "2026-02-27", "1/31 + 1개월 = 2/27 (없는 날짜는 말일로 당긴 뒤 −1일)")
eq(참여종료일계산("2024-01-01", 2), "2024-02-29", "윤년 2월을 넘긴다")
eq(참여종료일계산("2026-12-01", 1), "2026-12-31", "해를 안 넘긴다")
eq(참여종료일계산("2026-12-15", 1), "2027-01-14", "해를 넘긴다")
eq(참여종료일계산("2026-01-01", 0.5), null, "정수가 아니면 계산하지 않는다(짐작해 채우지 않는다)")
eq(참여종료일계산("", 6), null, "시작일이 없으면 계산하지 않는다")
eq(참여종료일계산("2026-01-01", 0), null, "0개월이면 계산하지 않는다")

console.log("\n② 국책만 합산 — 민간은 반영하지 않는다")
eq(국책인가("NATIONAL_RND"), true, "국가 R&D 는 합산한다")
eq(국책인가("LOCAL_TP"), true, "지자체·TP 도 합산한다")
eq(국책인가(null), true, "모르는 유형은 합산한다(빼면 초과를 놓쳐 정산에서 걸린다)")
eq(국책인가("PRIVATE"), false, "민간은 합산하지 않는다")

const 줄 = (o) => ({
  과제_id: o.p,
  과제코드: o.코드 ?? `P${o.p}`,
  사업유형: o.유형 ?? "NATIONAL_RND",
  표시명: o.이름 ?? "홍길동",
  참여율: o.율,
  참여시작일: o.시작 ?? "2026-01-01",
  참여종료일: o.끝 ?? "2026-12-31",
})

console.log("\n③ 같은 시점 합계 100% 초과")
eq(국책참여율_초과([줄({ p: 1, 율: 100 })]).length, 0, "딱 100% 는 통과한다")
eq(국책참여율_초과([줄({ p: 1, 율: 60 }), 줄({ p: 2, 율: 40 })]).length, 0, "60+40 = 100 통과")
const 초과1 = 국책참여율_초과([줄({ p: 1, 율: 60 }), 줄({ p: 2, 율: 50 })])
eq(초과1.length, 1, "60+50 = 110 은 잡힌다")
eq(초과1[0]?.합, 110, "합계를 그대로 말해 준다")
eq(
  초과1[0]?.메시지.includes("P1 60% + P2 50%"),
  true,
  "어느 과제 때문인지 말해 준다",
)
eq(초과1[0]?.메시지.includes("민간과제는 합산하지 않습니다"), true, "민간 제외를 안내한다")

console.log("\n④ 민간과제는 넘쳐도 안 잡는다")
eq(
  국책참여율_초과([줄({ p: 1, 율: 60 }), 줄({ p: 2, 율: 90, 유형: "PRIVATE" })]).length,
  0,
  "국책 60 + 민간 90 = 150 이어도 통과(민간은 반영 안 함)",
)

console.log("\n⑤ 기간이 안 겹치면 안 더한다 — 100% 는 「같은 시점」 기준이다")
eq(
  국책참여율_초과([
    줄({ p: 1, 율: 80, 시작: "2026-01-01", 끝: "2026-06-30" }),
    줄({ p: 2, 율: 80, 시작: "2026-07-01", 끝: "2026-12-31" }),
  ]).length,
  0,
  "상반기 80% + 하반기 80% 는 초과가 아니다",
)
eq(
  국책참여율_초과([
    줄({ p: 1, 율: 80, 시작: "2026-01-01", 끝: "2026-07-31" }),
    줄({ p: 2, 율: 80, 시작: "2026-07-01", 끝: "2026-12-31" }),
  ]).length,
  1,
  "하루라도 겹치면 잡는다",
)
eq(기간겹침({ 시작: null, 끝: null }, { 시작: "2026-01-01", 끝: "2026-12-31" }), true, "기간을 모르면 겹친다고 본다")

console.log("\n⑥ 사람이 다르면 안 더한다")
eq(
  국책참여율_초과([줄({ p: 1, 율: 90, 이름: "홍길동" }), 줄({ p: 2, 율: 90, 이름: "이몽룡" })]).length,
  0,
  "다른 사람의 참여율은 안 합친다",
)

console.log(실패 ? `\n✗ ${실패}건 실패` : "\n✓ 전 항목 통과")
process.exit(실패 ? 1 : 0)
