// 정산일 계산 검산. 브라우저가 필요 없다 — 순수 함수라 값으로 바로 본다.
//   npx tsc lib/settlement-day.ts --outDir /tmp/scheck --target es2022 --module esnext --moduleResolution bundler
//   node tests/settlement-check.mjs /tmp/scheck/settlement-day.js
const m = await import(process.argv[2] ?? "/tmp/scheck/settlement-day.js")
const { 다음정산일, 그달정산일, 직전영업일, 주말인가 } = m

let 실패 = 0
const eq = (실제, 기대, 말) => {
  const ok = JSON.stringify(실제) === JSON.stringify(기대)
  if (!ok) 실패++
  console.log(`   ${ok ? "✓" : "✗"} ${말}${ok ? "" : `  (얻은 값: ${JSON.stringify(실제)})`}`)
}

console.log("① 25일이 평일이면 그대로")
// 2026-08-25 는 화요일
eq(그달정산일(2026, 8).날, "2026-08-25", "2026-08 → 8/25(화) 그대로")
eq(그달정산일(2026, 11).날, "2026-11-25", "2026-11 → 11/25(수) 그대로")

console.log("\n② 주말이면 금요일로 당긴다 — 사용자가 말한 그 규칙")
// 2026-04-25 는 토요일 → 4/24(금)
eq(그달정산일(2026, 4).날, "2026-04-24", "4/25(토) → 4/24(금)")
eq(주말인가("2026-04-25"), true, "4/25 는 주말이다")
// 2026-10-25 는 일요일 → 10/23(금)
eq(그달정산일(2026, 10).날, "2026-10-23", "10/25(일) → 10/23(금)")

console.log("\n③ 공휴일이면 앞 영업일로")
// 2026-12-25 성탄절(금) → 12/24(목)
eq(그달정산일(2026, 12).날, "2026-12-24", "12/25 성탄절 → 12/24(목)")
// 2026-09-25 추석(공휴일 목록 기준) → 연휴를 넘어 9/23(수)
eq(그달정산일(2026, 9).날, "2026-09-23", "9/25 추석 연휴 → 9/23(수)")

console.log("\n④ 연휴를 통째로 넘는다")
eq(직전영업일("2026-09-26"), "2026-09-23", "9/24~26 연휴를 다 지나 9/23 으로")

console.log("\n⑤ D-day — 오늘 기준")
const a = 다음정산일("2026-09-04")
eq(a.날, "2026-09-23", "9/4 에서 다음 정산일은 9/23")
eq(a.남은일, 19, "D-19")
eq(a.당겨짐, true, "당겨졌다고 알려 준다")
eq(a.이유, "공휴일", "왜 당겨졌는지 말해 준다")
eq(a.확인필요, true, "음력 공휴일이 끼어 확인이 필요하다고 표시한다")

const b = 다음정산일("2026-09-23")
eq(b.남은일, 0, "정산일 당일은 D-0")
const c = 다음정산일("2026-09-24")
eq(c.날, "2026-10-23", "정산일이 지나면 다음 달로 넘어간다")
const d = 다음정산일("2026-12-26")
eq(d.날, "2027-01-25", "12월이 지나면 해를 넘긴다")
eq(d.요일, "월", "요일을 같이 준다")

console.log(실패 ? `\n✗ ${실패}건 실패` : "\n✓ 전 항목 통과")
process.exit(실패 ? 1 : 0)
