// 정산일 계산 검산. 브라우저 없이 값으로 본다.
//   npx tsc lib/settlement-day.ts --outDir /tmp/scheck --target es2022 --module esnext --moduleResolution bundler
//   node tests/settlement-check.mjs /tmp/scheck/settlement-day.js
const m = await import(process.argv[2] ?? "/tmp/scheck/settlement-day.js")
const { 다음정산일, 그달정산일, 기본규칙 } = m

let 실패 = 0
const eq = (실제, 기대, 말) => {
  const ok = JSON.stringify(실제) === JSON.stringify(기대)
  if (!ok) 실패++
  console.log(`   ${ok ? "✓" : "✗"} ${말}${ok ? "" : `  (얻은 값: ${JSON.stringify(실제)})`}`)
}

// db/114 시드와 같은 공휴일
const 공휴일 = [
  { 날짜: "2026-09-24", 이름: "추석 연휴", 확인필요: true },
  { 날짜: "2026-09-25", 이름: "추석", 확인필요: true },
  { 날짜: "2026-09-26", 이름: "추석 연휴", 확인필요: true },
  { 날짜: "2026-12-25", 이름: "성탄절", 확인필요: false },
]
const 규칙 = { 기준일: 25, 이동: "앞" }
const 그달 = (y, mm, r = 규칙, h = 공휴일, o = []) => 그달정산일(y, mm, r, h, o)

console.log("① 기본 — 매월 25일, 쉬는 날이면 앞으로")
eq(그달(2026, 8).날, "2026-08-25", "8/25(화) 그대로")
eq(그달(2026, 4).날, "2026-04-24", "4/25(토) → 4/24(금) — 주말은 당기면 금요일이다")
eq(그달(2026, 10).날, "2026-10-23", "10/25(일) → 10/23(금)")
eq(그달(2026, 12).날, "2026-12-24", "12/25 성탄절 → 12/24(목)")
eq(그달(2026, 9).날, "2026-09-23", "9/24~26 추석 연휴를 통째로 넘어 9/23(수)")
eq(그달(2026, 9).확인필요, true, "음력 공휴일이 끼면 확인 필요를 알린다")

console.log("\n② 규칙을 바꿀 수 있다 — 회계 일정은 매번 달라진다")
eq(그달(2026, 9, { 기준일: 10, 이동: "앞" }).날, "2026-09-10", "기준일을 10일로 바꾸면 9/10")
eq(그달(2026, 4, { 기준일: 25, 이동: "뒤" }).날, "2026-04-27", "「뒤로 미룸」이면 4/25(토) → 4/27(월)")
eq(그달(2026, 4, { 기준일: 25, 이동: "그대로" }).날, "2026-04-25", "「그대로」면 주말이어도 안 옮긴다")
eq(그달(2026, 2, { 기준일: 31, 이동: "그대로" }).날, "2026-02-28", "그 달에 없는 날(2/31)은 말일로 당긴다")

console.log("\n③ 그 달만 따로 잡은 날이 규칙을 이긴다")
const 콕 = [{ 연월: "2026-09", 마감일: "2026-09-27", 사유: "이번 달만 회계 마감이 늦다" }]
eq(그달(2026, 9, 규칙, 공휴일, 콕).날, "2026-09-27", "9월만 27일로 잡으면 그게 이긴다")
eq(그달(2026, 9, 규칙, 공휴일, 콕).달지정, true, "사람이 잡은 날이라고 표시한다")
eq(그달(2026, 10, 규칙, 공휴일, 콕).날, "2026-10-23", "다른 달은 규칙대로 간다")

console.log("\n④ 공휴일 목록도 데이터다 — 비면 평일로 본다")
eq(그달(2026, 9, 규칙, []).날, "2026-09-25", "공휴일을 안 넣으면 9/25(금) 그대로")
eq(그달(2026, 9, 규칙, []).확인필요, false, "그때는 확인 필요도 안 뜬다")

console.log("\n⑤ D-day")
const a = 다음정산일({ 규칙, 공휴일, 기준일: "2026-09-04" })
eq(a.날, "2026-09-23", "9/4 에서 다음 마감은 9/23")
eq(a.남은일, 19, "D-19")
eq(다음정산일({ 규칙, 공휴일, 기준일: "2026-09-23" }).남은일, 0, "당일은 D-0")
eq(다음정산일({ 규칙, 공휴일, 기준일: "2026-09-24" }).날, "2026-10-23", "지나면 다음 달")
// ⚠ 2027 공휴일이 아직 목록에 없다 — 1/25(월)이 그대로 마감이 된다.
//    **해가 바뀌기 전에 app.holidays 에 다음 해를 넣어야 한다.** 안 넣으면 조용히 평일로 계산된다.
eq(다음정산일({ 규칙, 공휴일, 기준일: "2026-12-26" }).날, "2027-01-25", "해를 넘긴다(2027 공휴일 미등록이라 25일 그대로)")
eq(기본규칙.기준일, 25, "기본값은 25일")

console.log(실패 ? `\n✗ ${실패}건 실패` : "\n✓ 전 항목 통과")
process.exit(실패 ? 1 : 0)
